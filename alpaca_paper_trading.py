def _send_deduped_submit_guard_alert(
    title: str,
    message: str,
    *,
    alert_key: str,
    priority: str = "warning",
    ttl_hours: float = 20.0,
) -> bool:
    """
    Send a submit guard alert once per dedupe window.

    PLAIN ENGLISH: If the same guard blocks the same tickers repeatedly during
    manual retries, the order log should still record every skip, but Telegram
    should not yell the exact same thing over and over.
    """
    now = datetime.now(timezone.utc)
    ttl = max(0.0, float(ttl_hours))
    cutoff = now - timedelta(hours=ttl)
    state: dict[str, str] = {}
    try:
        if ALERT_DEDUPE_FILE.exists():
            loaded = json.loads(ALERT_DEDUPE_FILE.read_text(encoding="utf-8"))
            if isinstance(loaded, dict):
                state = {str(k): str(v) for k, v in loaded.items()}
    except Exception:
        state = {}

    cleaned: dict[str, str] = {}
    for key, value in state.items():
        ts = pd.to_datetime(value, errors="coerce", utc=True)
        if pd.notna(ts) and ts.to_pydatetime() >= cutoff:
            cleaned[key] = value

    if alert_key in cleaned:
        print(f"  Alert deduped: {title} ({alert_key})")
        return False

    cleaned[alert_key] = now.isoformat()
    try:
        ALERT_DEDUPE_FILE.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_json(cleaned, ALERT_DEDUPE_FILE)
    except Exception:
        pass
    _send_submit_guard_alert(title, message, priority=priority)
    return True


def _order_status(broker: AlpacaBroker, oid: str) -> str:
    """Fetch one order status from Alpaca."""
    try:
        order = broker._api.get_order(oid)
        return str(getattr(order, "status", "") or "").lower()
    except Exception:
        return "query_failed"


def wait_for_order_fills(
    broker: AlpacaBroker,
    order_ids: list[str],
    *,
    timeout_seconds: float | None = None,
    poll_seconds: float | None = None,
) -> dict[str, str]:
    """
    Wait briefly for submitted sell orders to fill.

    PLAIN ENGLISH: Buy orders should not spend cash that sells have not freed
    yet.  This waits a short time for sell orders to become filled.
    """
    usable_ids = [oid for oid in order_ids if oid and not str(oid).startswith(("ERROR", "SKIPPED"))]
    if not usable_ids:
        return {}
    timeout = SELL_FILL_WAIT_SECONDS if timeout_seconds is None else float(timeout_seconds)
    poll = SELL_FILL_POLL_SECONDS if poll_seconds is None else float(poll_seconds)
    deadline = time.time() + max(0.0, timeout)
    statuses = {oid: _order_status(broker, oid) for oid in usable_ids}
    while time.time() < deadline and any(status not in {"filled", "canceled", "rejected", "expired"} for status in statuses.values()):
        if all(status == "filled" for status in statuses.values()):
            break
        time.sleep(max(0.5, poll))
        statuses = {oid: _order_status(broker, oid) for oid in usable_ids}
    return statuses


def _order_execution_snapshot(broker: AlpacaBroker, oid: str) -> dict:
    """Read status and partial-fill details for one broker order."""
    try:
        raw = broker._api.get_order(oid)
    except Exception:
        return {"status": "query_failed", "filled_qty": 0, "filled_avg_price": None}
    return {
        "status": str(getattr(raw, "status", "") or "").lower(),
        "filled_qty": int(float(getattr(raw, "filled_qty", 0) or 0)),
        "filled_avg_price": _float_or_none(getattr(raw, "filled_avg_price", None)),
    }


def _wait_for_cancel_terminal(broker: AlpacaBroker, oid: str) -> dict:
    """Wait briefly until a cancellation is final or a cancel/fill race resolves."""
    deadline = time.time() + max(0.0, EXECUTION_CANCEL_WAIT_SECONDS)
    snapshot = _order_execution_snapshot(broker, oid)
    terminal = {"filled", "canceled", "cancelled", "rejected", "expired"}
    while snapshot["status"] not in terminal and time.time() < deadline:
        time.sleep(max(0.05, EXECUTION_STAGE_POLL_SECONDS))
        snapshot = _order_execution_snapshot(broker, oid)
    return snapshot


def _submit_two_stage_limit(broker: AlpacaBroker, order_row: dict) -> str:
    """Try a passive midpoint limit, then reprice the confirmed remainder once."""
    ticker = str(order_row["ticker"]).upper()
    side = str(order_row["side"]).lower()
    requested_qty = int(order_row["quantity"])
    started = datetime.now(timezone.utc)
    stage1_wait, stage2_offset, price_policy = _two_stage_price_policy(order_row)
    quote, blocked_reason, quote_attempts = _submission_quote_with_retries(
        broker, ticker, side, extended_sell_retry=True
    )
    # Even blocked attempts retain the exact quote that caused the rejection.
    order_row.update({
        "bid_price": quote.get("bid_price"), "ask_price": quote.get("ask_price"),
        "quote_mid_price": quote.get("quote_mid_price"), "spread_pct": quote.get("spread_pct"),
        "quote_time": datetime.now(timezone.utc).isoformat(),
        "broker_quote_timestamp": quote.get("quote_timestamp"),
        "quote_age_seconds": _quote_age_seconds(quote),
        "quote_feed": quote.get("feed", ALPACA_DATA_FEED),
        "submission_quote_attempts": quote_attempts,
        "submission_quote_final_reason": blocked_reason,
    })
    if blocked_reason:
        order_row["execution_stage"] = "stage1_blocked"
        return _skip_order(order_row, blocked_reason)
    bid = _float_or_none(quote.get("bid_price"))
    ask = _float_or_none(quote.get("ask_price"))
    spread = _float_or_none(quote.get("spread_pct"))
    midpoint = _float_or_none(quote.get("quote_mid_price"))
    quote_age = _quote_age_seconds(quote)

    parent_id = bot_client_order_id(order_row)
    stage1_limit = passive_midpoint_limit_price(bid, ask, side)
    order_row.update({
        "parent_order_id": parent_id,
        "execution_stage": "stage1",
        "quote_time": started.isoformat(timespec="milliseconds"),
        "broker_quote_timestamp": quote.get("quote_timestamp") or "",
        "quote_age_seconds": round(quote_age, 3) if quote_age is not None else "",
        "bid_price": bid,
        "ask_price": ask,
        "quote_mid_price": midpoint if midpoint is not None else (bid + ask) / 2.0,
        "spread_pct": spread,
        "stage1_limit_price": stage1_limit,
        "stage1_wait_seconds": stage1_wait,
        "execution_price_policy": price_policy,
        "submitted_order_type": "limit",
        "submitted_limit_reference": "passive_midpoint",
        "submitted_limit_price": stage1_limit,
    })
    stage1 = Order(
        ticker=ticker,
        side=side,
        quantity=requested_qty,
        type="limit",
        limit_price=stage1_limit,
        client_id=bot_client_order_id(order_row, attempt=1),
    )
    stage1_oid = broker.place_order(stage1)
    order_row["stage1_order_id"] = stage1_oid
    wait_for_order_fills(
        broker,
        [stage1_oid],
        timeout_seconds=stage1_wait,
        poll_seconds=EXECUTION_STAGE_POLL_SECONDS,
    )
    stage1_state = _order_execution_snapshot(broker, stage1_oid)
    order_row["stage1_status"] = stage1_state["status"]
    order_row["stage1_filled_qty"] = stage1_state["filled_qty"]
    order_row["stage1_filled_avg_price"] = stage1_state["filled_avg_price"] or ""
    if stage1_state["status"] == "filled" or stage1_state["filled_qty"] >= requested_qty:
        order_row["fill_latency_seconds"] = round((datetime.now(timezone.utc) - started).total_seconds(), 3)
        order_row["fill_status"] = "filled"
        order_row["filled_qty"] = requested_qty
        order_row["filled_avg_price"] = stage1_state["filled_avg_price"] or ""
        print(f"    ✓ {side.upper()} {requested_qty} {ticker} passive limit=${stage1_limit:.2f} → filled")
        return stage1_oid

    cancel_requested = bool(broker.cancel_order(stage1_oid))
    cancel_state = _wait_for_cancel_terminal(broker, stage1_oid)
    order_row["stage1_cancel_requested"] = cancel_requested
    order_row["stage1_cancel_status"] = cancel_state["status"]
    stage1_filled_qty = max(stage1_state["filled_qty"], cancel_state["filled_qty"])
    stage1_fill_price = cancel_state["filled_avg_price"] or stage1_state["filled_avg_price"]
    order_row["stage1_filled_qty"] = stage1_filled_qty
    order_row["stage1_filled_avg_price"] = stage1_fill_price or ""
    if cancel_state["status"] == "filled" or stage1_filled_qty >= requested_qty:
        order_row["execution_stage"] = "stage1_cancel_fill_race"
        order_row["fill_status"] = "filled"
        order_row["filled_qty"] = requested_qty
        order_row["filled_avg_price"] = stage1_fill_price or ""
        order_row["fill_latency_seconds"] = round((datetime.now(timezone.utc) - started).total_seconds(), 3)
        return stage1_oid

    if not cancel_requested or cancel_state["status"] not in {"canceled", "cancelled", "rejected", "expired"}:
        order_row["execution_stage"] = "cancel_uncertain"
        order_row["fill_status"] = "partially_filled" if stage1_filled_qty else "pending_cancel"
        order_row["filled_qty"] = stage1_filled_qty
        order_row["filled_avg_price"] = stage1_fill_price or ""
        _send_submit_guard_alert(
            "Two-stage cancel uncertain",
            f"{ticker} stage-1 cancellation was not confirmed; no replacement order was sent.",
            priority="critical",
        )
        return stage1_oid

    remaining_qty = max(0, requested_qty - stage1_filled_qty)
    order_row["remaining_quantity"] = remaining_qty
    if remaining_qty == 0:
        order_row["fill_status"] = "filled"
        return stage1_oid

    second_quote, blocked_reason, second_quote_attempts = _submission_quote_with_retries(
        broker, ticker, side, extended_sell_retry=True
    )
    second_bid = _float_or_none(second_quote.get("bid_price"))
    second_ask = _float_or_none(second_quote.get("ask_price"))
    second_spread = _float_or_none(second_quote.get("spread_pct"))
    second_quote_age = _quote_age_seconds(second_quote)
    order_row.update({
        "stage2_quote_time": datetime.now(timezone.utc).isoformat(),
        "stage2_broker_quote_timestamp": second_quote.get("quote_timestamp"),
        "stage2_bid_price": second_bid, "stage2_ask_price": second_ask,
        "stage2_spread_pct": second_spread, "stage2_quote_age_seconds": second_quote_age,
        "stage2_quote_feed": second_quote.get("feed", ALPACA_DATA_FEED),
        "stage2_quote_attempts": second_quote_attempts,
    })
    if blocked_reason:
        order_row["stage2_block_reason"] = blocked_reason
        order_row["execution_stage"] = "stage2_blocked"
        order_row["fill_status"] = "partially_filled" if stage1_filled_qty else "canceled"
        order_row["filled_qty"] = stage1_filled_qty
        order_row["filled_avg_price"] = stage1_fill_price or ""
        _send_submit_guard_alert(
            "Two-stage reprice blocked",
            f"{ticker} replacement blocked: {blocked_reason}.",
        )
        return stage1_oid

    stage2_limit = quote_based_limit_price(
        bid_price=second_bid,
        ask_price=second_ask,
        fallback_price=order_row.get("price"),
        side=side,
        ticker=ticker,
        limit_offset_bps=stage2_offset,
    )
    stage2 = Order(
        ticker=ticker,
        side=side,
        quantity=remaining_qty,
        type="limit",
        limit_price=stage2_limit,
        client_id=bot_client_order_id(order_row, attempt=2),
    )
    try:
        stage2_oid = broker.place_order(stage2)
    except Exception as exc:
        order_row["execution_stage"] = "stage2_failed"
        order_row["stage2_error"] = str(exc)
        order_row["fill_status"] = "partially_filled" if stage1_filled_qty else "canceled"
        order_row["filled_qty"] = stage1_filled_qty
        order_row["filled_avg_price"] = stage1_fill_price or ""
        _send_submit_guard_alert("Two-stage replacement failed", f"{ticker} replacement failed: {exc}", priority="critical")
        return stage1_oid
    order_row.update({
        "execution_stage": "stage2",
        "stage2_order_id": stage2_oid,
        "stage2_quote_time": datetime.now(timezone.utc).isoformat(timespec="milliseconds"),
        "stage2_bid_price": second_bid,
        "stage2_ask_price": second_ask,
        "stage2_spread_pct": second_spread,
        "stage2_quote_age_seconds": round(second_quote_age, 3) if second_quote_age is not None else "",
        "stage2_limit_price": stage2_limit,
        "stage2_offset_bps": stage2_offset,
        "stage2_quantity": remaining_qty,
        "submitted_limit_reference": "stage2_quote_cap",
        "submitted_limit_price": stage2_limit,
        "fill_status": "pending",
    })
    print(f"    ✓ {side.upper()} {remaining_qty} {ticker} repriced limit=${stage2_limit:.2f} → order_id={stage2_oid[:12]}...")
    return stage2_oid


def _submit_one_rebalance_order(
    broker: AlpacaBroker,
    order_row: dict,
    *,
    use_market_order: bool,
    use_quote_limit: bool,
) -> str:
    """Submit one planned rebalance order and return the Alpaca id or ERROR."""
    try:
        if (
            TWO_STAGE_EXECUTION_ENABLED
            and not use_market_order
            and use_quote_limit
            and hasattr(broker, "get_quote_snapshot")
            and hasattr(broker, "cancel_order")
        ):
            return _submit_two_stage_limit(broker, order_row)
        # Each queued order needs a new quote; an earlier planning check can expire.
        quote, reason, quote_attempts = _submission_quote_with_retries(
            broker,
            str(order_row["ticker"]),
            str(order_row.get("side", "")),
            extended_sell_retry=True,
        )
        order_row.update(quote)
        order_row.update(broker_quote_timestamp=quote.get("quote_timestamp"),
                         quote_age_seconds=_quote_age_seconds(quote),
                         quote_time=datetime.now(timezone.utc).isoformat(),
                         quote_feed=quote.get("feed", ALPACA_DATA_FEED),
                         submission_quote_attempts=quote_attempts,
                         submission_quote_final_reason=reason)
        if reason:
            return _skip_order(order_row, reason)
        order = build_submission_order(
            order_row,
            use_market_order=use_market_order,
            use_quote_limit=use_quote_limit,
            client_id=bot_client_order_id(order_row),
        )
        oid = broker.place_order(order)
        limit_note = f" limit=${order.limit_price:.2f}" if order.type == "limit" and order.limit_price else ""
        print(f"    ✓ {order_row['side'].upper()} {order_row['quantity']} {order_row['ticker']} "
              f"{order.type}{limit_note} → order_id={oid[:12]}...")
        return oid
    except Exception as exc:
        print(f"    ✗ {order_row['side'].upper()} {order_row['quantity']} {order_row['ticker']} "
              f"FAILED: {exc}")
        return f"ERROR: {exc}"


def _skip_order(order_row: dict, reason: str) -> str:
    """Mark a planned order as intentionally skipped before submission."""
    order_row["submitted_order_type"] = "skipped"
    order_row["submitted_limit_price"] = ""
    order_row["submitted_limit_reference"] = reason
    order_row["fill_status"] = "skipped"
    print(f"    - SKIP {order_row['side'].upper()} {order_row['quantity']} {order_row['ticker']}: {reason}")
    return f"SKIPPED: {reason}"


def _write_broker_truth_gate_report() -> dict:
    """Refresh broker truth files immediately before live submission."""
    # Import inside the function so broker_truth.py can safely import the Alpaca
    # broker class from this script without creating a startup import loop.
    from broker_truth import write_broker_truth

    return write_broker_truth(include_live_open_orders=True)


def _broker_truth_issue_summary(payload: dict, limit: int = 5) -> str:
    """Return a compact reason string for Telegram/log messages."""
    issues: list[str] = []
    for item in payload.get("global_issues", []) or []:
        severity = str(item.get("severity", "")).lower()
        issue = str(item.get("issue", "")).strip()
        if severity in {"fail", "warning"} and issue:
            issues.append(issue)
    for row in payload.get("rows", []) or []:
        severity = str(row.get("issue_severity", "")).lower()
        if severity not in {"fail", "warning"}:
            continue
        ticker = str(row.get("ticker", "")).upper()
        row_issues = str(row.get("issues", "")).strip()
        if ticker or row_issues:
            issues.append(f"{ticker}:{row_issues}" if ticker else row_issues)
    if not issues:
        return "no detailed issues reported"
    summary = "; ".join(issues[:limit])
    if len(issues) > limit:
        summary += f"; +{len(issues) - limit} more"
    return summary


def _apply_broker_truth_gate(
    orders: list[dict],
    *,
    force: bool = False,
) -> tuple[list[dict], list[dict], list[str]]:
    """
    Skip BUY orders when broker truth is failing before live submission.

    PLAIN ENGLISH: if the broker account, local log, and target plan already
    disagree badly, adding new BUY risk can compound the mess.  SELL orders are
    still allowed so the bot can reduce exposure and clean up.
    """
    if not BROKER_TRUTH_GATE_ENABLED:
        return orders, [], []

    gate_failed = False
    fail_reason = ""
    try:
        payload = _write_broker_truth_gate_report()
        status = str(payload.get("status", "unknown")).strip().lower()
        counts = payload.get("summary", {}) or {}
        score = payload.get("score", "")
        print(
            "  Broker truth gate: "
            f"{status.upper()} score={score} "
            f"fail={counts.get('fail_count', 0)} warn={counts.get('warning_count', 0)}"
        )
        gate_failed = status == "fail"
        fail_reason = "broker_truth_fail"
        issue_summary = _broker_truth_issue_summary(payload)
    except Exception as exc:
        gate_failed = True
        fail_reason = f"broker_truth_gate_error:{type(exc).__name__}"
        issue_summary = str(exc)
        print(f"  WARNING: Broker truth gate could not refresh report: {exc}")

    if not gate_failed or not BROKER_TRUTH_BLOCK_BUYS_ON_FAIL:
        return orders, [], []

    buy_orders = [o for o in orders if str(o.get("side", "")).lower() == "buy"]
    if force or not buy_orders:
        override_note = " --force override active" if force and buy_orders else "sell-only plan"
        print(f"  Broker truth gate failed, but proceeding with {override_note}.")
        _send_submit_guard_alert(
            "Broker truth gate warning",
            f"Broker truth is failing before submit, proceeding with {override_note}.\n{issue_summary}",
            priority="warning",
        )
        return orders, [], []

    remaining: list[dict] = []
    skipped_orders: list[dict] = []
    skipped_ids: list[str] = []
    for order_row in orders:
        if str(order_row.get("side", "")).lower() == "buy":
            skipped_orders.append(order_row)
            skipped_ids.append(_skip_order(order_row, fail_reason))
        else:
            remaining.append(order_row)

    tickers = ", ".join(str(o.get("ticker", "")).upper() for o in skipped_orders)
    _send_submit_guard_alert(
        "Broker truth gate blocked buys",
        (
            f"Broker truth failed before submit, so BUY orders were skipped: {tickers}.\n"
            f"SELL orders are still allowed.\n{issue_summary}"
        ),
        priority="critical",
    )
    return remaining, skipped_orders, skipped_ids


def _apply_spread_guard(
    broker: AlpacaBroker,
    orders: list[dict],
    *,
    sleep_fn=time.sleep,
) -> tuple[list[dict], list[dict], list[str]]:
    """
    Remove orders that have unsafe or unverifiable bid-ask spreads.

    PLAIN ENGLISH: Before an order is sent, we ask Alpaca for the current bid
    and ask. If the spread is too wide or a fresh valid quote is unavailable,
    the order is logged as skipped instead of simply
    disappearing from the run.
    """
    remaining: list[dict] = []
    skipped_orders: list[dict] = []
    skipped_ids: list[str] = []

    for order_row in orders:
        ticker = str(order_row.get("ticker", "")).upper()
        first_quote: dict | None = None
        quote: dict = {}
        reason = "quote_unavailable"
        side = str(order_row.get("side", "")).lower()
        # Sells are not discarded by this preliminary pass. Their definitive
        # check happens in sell-first submission with the extended retry budget,
        # so a momentary quote cannot prevent the recovery logic from running.
        quote, reason, attempts_used = _submission_quote_with_retries(
            broker,
            ticker,
            side,
            extended_sell_retry=False,
            sleep_fn=sleep_fn,
        )
        first_quote = dict(quote)

        arrival_quote = first_quote or quote
        order_row.setdefault("arrival_mid", arrival_quote.get("quote_mid_price"))
        order_row.setdefault("arrival_quote_timestamp", arrival_quote.get("quote_timestamp"))
        order_row.setdefault("arrival_feed", arrival_quote.get("feed", "unknown"))
        arrival_spread = _float_or_none(arrival_quote.get("spread_pct"))
        order_row.setdefault("arrival_spread_bps", arrival_spread * 10000 if arrival_spread is not None else None)
        order_row.setdefault("original_requested_quantity", order_row.get("quantity"))
        order_row["spread_guard_quote_attempts"] = attempts_used
        order_row.update({
            "bid_price": quote.get("bid_price"),
            "ask_price": quote.get("ask_price"),
            "quote_mid_price": quote.get("quote_mid_price"),
            "spread_pct": quote.get("spread_pct"),
            "broker_quote_timestamp": quote.get("quote_timestamp"),
            "quote_age_seconds": _quote_age_seconds(quote),
            "quote_feed": quote.get("feed", ALPACA_DATA_FEED),
        })

        if reason:
            if side == "sell":
                order_row["spread_guard_precheck_reason"] = reason
                remaining.append(order_row)
                continue
            skipped_orders.append(order_row)
            skipped_ids.append(_skip_order(order_row, reason))
            continue

        remaining.append(order_row)

    if skipped_orders:
        tickers = ", ".join(str(o.get("ticker", "")).upper() for o in skipped_orders)
        reasons = ",".join(
            str(o.get("submitted_limit_reference", "")).replace(" ", "_")
            for o in skipped_orders
        )
        alert_key = f"spread_guard:{datetime.now(timezone.utc).date()}:{tickers}:{reasons}"
        _send_deduped_submit_guard_alert(
            "Spread Guard",
            f"Spread/quote guard blocked {len(skipped_orders)} orders: {tickers}",
            alert_key=alert_key,
            priority="warning",
            ttl_hours=SPREAD_GUARD_ALERT_TTL_HOURS,
        )

    return remaining, skipped_orders, skipped_ids


def _buy_cash_reserve_price(order_row: dict, *, use_market_order: bool) -> float | None:
    """
    Return the per-share cash reserve price for a buy order.

    PLAIN ENGLISH: Alpaca reserves cash differently by order type.  For a
    limit buy, cash must cover the limit price.  For a market buy, the best
    estimate before sending is the plan price.
    """
    if use_market_order:
        price = _float_or_none(order_row.get("price"))
    else:
        price = (
            _float_or_none(order_row.get("submitted_limit_price"))
            or _float_or_none(order_row.get("limit_price"))
            or _float_or_none(order_row.get("price"))
        )
    if price is None or price <= 0 or not np.isfinite(price):
        return None
    return float(price)


def _buy_cash_reserve_value(order_row: dict, *, use_market_order: bool) -> float:
    """Return how much cash one planned buy should reserve before submission."""
    reserve_price = _buy_cash_reserve_price(order_row, use_market_order=use_market_order)
    quantity = _float_or_none(order_row.get("quantity"))
    if reserve_price is None or quantity is None:
        return 0.0
    return max(0.0, int(quantity) * reserve_price)


def _buy_spendable_cash(broker: AlpacaBroker, cash: float) -> float:
    """
    Return cash safe to spend after broker buying-power reservations.

    PLAIN ENGLISH: Alpaca may reserve buying power for open orders before cash
    changes.  We use min(cash, buying power) so pending buys cannot trick the
    bot into thinking more cash is free.
    """
    buying_power = None
    getter = getattr(broker, "get_buying_power", None)
    if callable(getter):
        try:
            buying_power = _float_or_none(getter())
        except Exception as exc:
            print(f"  ⚠ Could not check buying power before buys: {exc}")
    if buying_power is None:
        return float(cash)
    return min(float(cash), float(buying_power))


def _buy_cash_buffer_amount(broker: AlpacaBroker) -> float:
    """
    Return the cash cushion to keep unused after the buy phase.

    PLAIN ENGLISH: This leaves breathing room for small price moves, broker
    rounding, fees, and pending-order accounting instead of spending the account
    down to almost zero cash.
    """
    dollar_buffer = max(0.0, BUY_CASH_BUFFER_DOLLARS)
    buffer_equity = 0.0
    if BUY_CASH_BUFFER_PCT > 0:
        try:
            equity = _float_or_none(broker.get_equity())
            if equity is not None and equity > 0:
                buffer_equity = equity
        except Exception as exc:
            print(f"  ⚠ Could not compute percent cash buffer: {exc}")
    from paper_policy import cash_reserve
    return cash_reserve(buffer_equity, BUY_CASH_BUFFER_PCT, dollar_buffer)


def _fit_buy_orders_to_available_cash(
    buy_orders: list[dict],
    cash_available: float,
    *,
    use_market_order: bool,
) -> tuple[list[dict], list[tuple[dict, str]], float]:
    """
    Shrink buy quantities so the whole buy phase fits available cash.

    PLAIN ENGLISH: If the plan wants 163 shares but available cash only covers
    160 shares at the limit price, submit 160 instead of skipping the whole
    order.  It only shrinks buys; it never borrows, rounds up, or touches sells.
    """
    adjusted: list[dict] = []
    skipped: list[tuple[dict, str]] = []
    cash_limit = max(0.0, float(cash_available))
    candidates: list[dict] = []

    for index, order_row in enumerate(buy_orders):
        reserve_price = _buy_cash_reserve_price(order_row, use_market_order=use_market_order)
        requested_quantity = _float_or_none(order_row.get("quantity"))
        original_quantity = max(0, int(requested_quantity or 0))
        if reserve_price is None or reserve_price <= 0 or original_quantity <= 0:
            skipped.append((order_row, "invalid_cash_reserve_price"))
            continue
        candidates.append({
            "index": index,
            "row": order_row,
            "price": float(reserve_price),
            "original": original_quantity,
            "allocated": 0,
        })

    requested_value = sum(item["original"] * item["price"] for item in candidates)
    scale = min(1.0, cash_limit / requested_value) if requested_value > 0 else 0.0
    # Start every order at the same fraction of its requested shares. This avoids
    # spending all available cash on whichever ticker happened to sort first.
    for item in candidates:
        item["allocated"] = min(item["original"], int(math.floor(item["original"] * scale)))

    spent = sum(item["allocated"] * item["price"] for item in candidates)
    remaining_cash = max(0.0, cash_limit - spent)
    # Whole-share rounding leaves spare cash. Give one share at a time to the
    # most underfilled order; ticker/index make equal cases deterministic.
    while True:
        affordable = [
            item for item in candidates
            if item["allocated"] < item["original"] and item["price"] <= remaining_cash + 1e-9
        ]
        if not affordable:
            break
        chosen = min(
            affordable,
            key=lambda item: (
                item["allocated"] / item["original"],
                -float(item["row"].get("target_weight", 0) or 0),
                item["index"],
            ),
        )
        chosen["allocated"] += 1
        remaining_cash -= chosen["price"]

    for item in candidates:
        order_row = item["row"]
        reserve_price = item["price"]
        original_quantity = item["original"]
        affordable_quantity = item["allocated"]
        if affordable_quantity <= 0:
            skipped.append((order_row, (
                f"insufficient_cash_for_one_share:available_cash={cash_limit:.2f};"
                f"reserve_px={reserve_price:.2f}"
            )))
            continue
        if affordable_quantity * reserve_price < MIN_TRADE_VALUE:
            skipped.append((order_row, (
                f"cash_clamped_below_min_trade:{affordable_quantity * reserve_price:.2f}"
                f"<{MIN_TRADE_VALUE:.2f}"
            )))
            remaining_cash += affordable_quantity * reserve_price
            continue

        if affordable_quantity < original_quantity:
            mark_price = _float_or_none(order_row.get("price")) or reserve_price
            order_row["original_quantity_before_cash_clamp"] = original_quantity
            order_row["quantity"] = affordable_quantity
            order_row["cash_clamped_to_available"] = True
            order_row["cash_clamp_reason"] = (
                f"proportional_cash_limited:{original_quantity}->{affordable_quantity};"
                f"cash_available={cash_limit:.2f};reserve_px={reserve_price:.2f}"
            )
            order_row["trade_value"] = round(abs(affordable_quantity * mark_price), 6)
            print(
                f"    CASH CLAMP {order_row['ticker']}: "
                f"{original_quantity} -> {affordable_quantity} shares "
                f"(shared cash ${cash_limit:,.2f}, reserve ${reserve_price:,.2f}/share)"
            )
        else:
            order_row.setdefault("original_quantity_before_cash_clamp", "")
            order_row.setdefault("cash_clamped_to_available", False)
            order_row.setdefault("cash_clamp_reason", "")
        adjusted.append(order_row)

    return adjusted, skipped, max(0.0, remaining_cash)


def submit_rebalance_orders(
    broker: AlpacaBroker,
    orders: list[dict],
    *,
    use_market_order: bool,
    use_quote_limit: bool,
) -> tuple[list[dict], list[str]]:
    """
    Submit sells first, then buys only if cash is actually safe.

    PLAIN ENGLISH: If a sell fails or does not fill, a buy can accidentally
    turn into margin.  This guard skips buys instead of borrowing.
    """
    attempted_orders: list[dict] = []
    order_ids: list[str] = []
    for order_row in orders:
        # Capture requested shares before any cash clamp or replacement sizing.
        order_row.setdefault("original_requested_quantity", order_row.get("quantity"))
    sell_orders = [o for o in orders if str(o.get("side", "")).lower() == "sell"]
    buy_orders = [o for o in orders if str(o.get("side", "")).lower() == "buy"]
    cash_skipped_buy_orders: list[tuple[dict, str]] = []
    cash_clamp_note = ""

    sell_ids: list[str] = []
    sell_phase_issues: list[str] = []
    if sell_orders:
        print("  Phase 1/2: submitting sells first...")
    for order_row in sell_orders:
        oid = _submit_one_rebalance_order(
            broker,
            order_row,
            use_market_order=use_market_order,
            use_quote_limit=use_quote_limit,
        )
        attempted_orders.append(order_row)
        order_ids.append(oid)
        sell_ids.append(oid)
        # A failed sell has not freed cash, but it must not block purchases that
        # the broker confirms are affordable from cash already on hand.
        if str(oid).startswith(("ERROR", "SKIPPED")):
            sell_phase_issues.append(str(oid))

    skip_buy_reason = ""
    if buy_orders:
        usable_sell_ids = [oid for oid in sell_ids if not str(oid).startswith(("ERROR", "SKIPPED"))]
        if usable_sell_ids and SKIP_BUYS_UNTIL_SELLS_FILLED:
            print(f"  Waiting up to {SELL_FILL_WAIT_SECONDS:g}s for sells to fill before buys...")
            statuses = wait_for_order_fills(broker, usable_sell_ids)
            unfilled = {oid: status for oid, status in statuses.items() if status != "filled"}
            if unfilled:
                status_note = ", ".join(f"{oid[:8]}={status}" for oid, status in list(unfilled.items())[:4])
                sell_phase_issues.append(f"sell_not_filled:{status_note}")
        if sell_phase_issues:
            issue_note = ";".join(sell_phase_issues[:4])
            print(f"  Sell phase incomplete; sizing buys from verified cash only: {issue_note}")
            for order_row in buy_orders:
                order_row["sell_phase_issues"] = issue_note
        if not skip_buy_reason and SKIP_BUYS_WHEN_CASH_BELOW > -1e12:
            try:
                cash = broker.get_cash()
                if cash < SKIP_BUYS_WHEN_CASH_BELOW:
                    skip_buy_reason = f"cash_below_threshold:{cash:.2f}"
                else:
                    spendable_cash = _buy_spendable_cash(broker, cash)
                    cash_floor = max(0.0, SKIP_BUYS_WHEN_CASH_BELOW)
                    cash_buffer = max(cash_floor, _buy_cash_buffer_amount(broker))
                    cash_available = max(0.0, spendable_cash - cash_buffer)
                    if spendable_cash < cash - 1.0:
                        print(
                            f"  Buy cash check uses buying power ${spendable_cash:,.2f} "
                            f"instead of raw cash ${cash:,.2f}"
                        )
                    if cash_buffer > 0:
                        print(
                            f"  Buy cash buffer reserved: ${cash_buffer:,.2f}; "
                            f"available for buys: ${cash_available:,.2f}"
                        )
                    for order_row in buy_orders:
                        order_row["cash_buffer_reserved"] = round(cash_buffer, 2)
                        order_row["cash_available_after_buffer"] = round(cash_available, 2)
                        order_row["buying_power_used_for_cash_check"] = round(spendable_cash, 2)
                    total_buy_value = sum(
                        _buy_cash_reserve_value(o, use_market_order=use_market_order)
                        for o in buy_orders
                    )
                    if total_buy_value > cash_available + 1.0:
                        original_buy_count = len(buy_orders)
                        buy_orders, cash_skipped_buy_orders, cash_left = _fit_buy_orders_to_available_cash(
                            buy_orders,
                            cash_available,
                            use_market_order=use_market_order,
                        )
                        cash_clamp_note = (
                            f"planned_buy_reserve={total_buy_value:.2f} "
                            f"available_cash={cash_available:.2f}; "
                            f"cash_buffer={cash_buffer:.2f}; "
                            f"buying_power_check={spendable_cash:.2f}; "
                            f"adjusted={len(buy_orders)}/{original_buy_count}; "
                            f"skipped={len(cash_skipped_buy_orders)}; cash_left={cash_left:.2f}"
                        )
            except Exception as exc:
                # PLAIN ENGLISH: A broker/account read failure means we do not
                # know whether the account can afford the buys.  Selling can
                # still reduce risk, but submitting unchecked buys could create
                # margin, so the buy phase must fail closed.
                skip_buy_reason = f"cash_safety_check_failed:{type(exc).__name__}"
                print(f"  ⚠ Could not check cash before buys; buys will be skipped: {exc}")

    if buy_orders and skip_buy_reason:
        print(f"  Buy phase skipped: {skip_buy_reason}")
        _send_submit_guard_alert(
            "Alpaca buy phase skipped",
            f"Buy orders skipped to avoid margin/leverage.\nReason: {skip_buy_reason}",
        )
        for order_row in buy_orders:
            attempted_orders.append(order_row)
            order_ids.append(_skip_order(order_row, skip_buy_reason))
        return attempted_orders, order_ids

    if cash_clamp_note:
        print(f"  Buy phase cash-fit: {cash_clamp_note}")
        _send_submit_guard_alert(
            "Alpaca buy orders cash-fit",
            (
                "Buy orders were shrunk or skipped to avoid margin/leverage.\n"
                f"{cash_clamp_note}"
            ),
        )

    for order_row, reason in cash_skipped_buy_orders:
        attempted_orders.append(order_row)
        order_ids.append(_skip_order(order_row, reason))

    if buy_orders:
        print("  Phase 2/2: submitting buys...")
    for order_row in buy_orders:
        oid = _submit_one_rebalance_order(
            broker,
            order_row,
            use_market_order=use_market_order,
            use_quote_limit=use_quote_limit,
        )
        attempted_orders.append(order_row)
        order_ids.append(oid)

    return attempted_orders, order_ids


def warn_if_margin_exposure(broker: AlpacaBroker) -> dict:
    """
    Warn when Alpaca stock value is materially higher than account equity.

    PLAIN ENGLISH: If stock value is higher than equity, cash is negative and
    the account is using margin.  This only warns; it does not trade.
    """
    try:
        account = broker._api.get_account()
        equity = float(getattr(account, "equity", 0) or 0)
        cash = float(getattr(account, "cash", 0) or 0)
        long_market_value = _float_or_none(getattr(account, "long_market_value", None))
        if long_market_value is None:
            long_market_value = equity - cash
    except Exception:
        try:
            equity = broker.get_equity()
            cash = broker.get_cash()
            long_market_value = equity - cash
        except Exception as exc:
            print(f"  ⚠ Could not check margin exposure: {exc}")
            return {"ok": False, "error": str(exc)}

    gross = long_market_value / equity if equity > 0 else 0.0
    result = {
        "ok": gross <= MARGIN_WARN_GROSS and cash >= 0,
        "equity": equity,
        "cash": cash,
        "long_market_value": long_market_value,
        "gross": gross,
    }
    if not result["ok"]:
        msg = (
            f"Alpaca account is using margin/leverage.\n"
            f"Equity: ${equity:,.2f}\n"
            f"Stock value: ${long_market_value:,.2f}\n"
            f"Cash: ${cash:,.2f}\n"
            f"Gross: {gross:.2f}x"
        )
        print(f"  ⚠ Margin exposure warning: stock value ${long_market_value:,.2f}, "
              f"equity ${equity:,.2f}, cash ${cash:,.2f}, gross {gross:.2f}x")
        _send_submit_guard_alert("Alpaca margin exposure", msg)
    return result


def _already_submitted_today(broker: AlpacaBroker | None = None) -> bool:
    """
    Check if orders were already submitted today.

    PLAIN ENGLISH: Prevents double-ordering.  If you accidentally run
    --submit twice in one day, the second run will warn you instead of
    placing duplicate trades.
    """
    broker_check_succeeded = broker is None
    broker_error = ""
    if broker is not None:
        try:
            alpaca_orders = _alpaca_rebalance_orders_submitted_today(broker)
            broker_check_succeeded = True
            if alpaca_orders:
                tickers = ", ".join(
                    f"{o['ticker']} {o['side']} {o['qty']:g}" for o in alpaca_orders[:6]
                )
                suffix = "..." if len(alpaca_orders) > 6 else ""
                print(f"  Alpaca already has bot orders today: {tickers}{suffix}")
                return True
        except Exception as exc:
            broker_error = str(exc)
            print(f"  ⚠ Could not check Alpaca duplicate orders; falling back to local log: {exc}")

    if not PAPER_LOG_FILE.exists():
        if broker is not None and not broker_check_succeeded:
            raise RuntimeError(
                "duplicate-order check is uncertain: Alpaca history failed and local log is missing"
                f" ({broker_error})"
            )
        return False
    try:
        log = pd.read_csv(PAPER_LOG_FILE)
        if log.empty:
            return False
        # Check for submissions from today (UTC)
        ts_col = "submitted_at" if "submitted_at" in log.columns else "timestamp"
        if ts_col not in log.columns:
            return False
        dates = pd.to_datetime(log[ts_col], errors="coerce", utc=True)
        today = pd.Timestamp.now(tz="UTC").normalize()
        today_rows = log[dates.dt.normalize() == today].copy()
        if today_rows.empty:
            return False
        fill_status = (
            today_rows.get("fill_status", pd.Series("", index=today_rows.index))
            .astype(str)
            .str.lower()
            .str.strip()
        )
        order_id_col = today_rows.get("order_id", pd.Series("", index=today_rows.index)).astype(str)
        # PLAIN ENGLISH: A skipped/error row means the bot did NOT reach Alpaca.
        # It should show in the audit log, but it should not block a later retry
        # if cash/quotes recover and no live Alpaca bot order exists.
        actually_sent = ~(
            fill_status.isin({"skipped", "submission_failed"})
            | order_id_col.str.startswith(("SKIPPED", "ERROR"), na=False)
        )
        return bool(actually_sent.any())
    except Exception as exc:
        if broker is not None and not broker_check_succeeded:
            raise RuntimeError(
                "duplicate-order check is uncertain: Alpaca history and local log are unreadable"
                f" ({broker_error}; {exc})"
            ) from exc
        return False


