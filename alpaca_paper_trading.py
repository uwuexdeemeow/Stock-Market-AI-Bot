def _truthy(value: object) -> bool:
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"true", "1", "yes", "y"}


def _float_or_none(value: object) -> float | None:
    """Convert a value to a finite float, or None if it is blank/bad."""
    try:
        out = float(value)
    except (TypeError, ValueError):
        return None
    if not np.isfinite(out):
        return None
    return out


def _limit_offset_bps(ticker: str) -> float:
    """Return the small price cushion used for marketable limit orders."""
    return LIMIT_OFFSET_BPS_ETF if str(ticker).upper() in ETF_TICKERS else LIMIT_OFFSET_BPS_OVERLAY


def _parse_report_timestamp(value: object) -> datetime | None:
    """Turn a JSON timestamp into a timezone-aware datetime when possible."""
    if not value:
        return None
    try:
        stamp = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None
    if stamp.tzinfo is None:
        stamp = stamp.replace(tzinfo=timezone.utc)
    return stamp.astimezone(timezone.utc)


def _load_execution_risk_map(now: datetime | None = None) -> dict[str, dict]:
    """
    Load recent per-symbol execution risk scores from the slippage report.

    PLAIN ENGLISH: If a ticker recently had bad fills or bad reversals after
    fills, this returns that score so order planning can be more careful.
    """
    if not EXECUTION_RISK_ENABLED or not SLIPPAGE_REPORT_FILE.exists():
        return {}
    try:
        report = json.loads(SLIPPAGE_REPORT_FILE.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}

    generated_at = _parse_report_timestamp(report.get("generated_at"))
    max_age_hours = max(0.0, float(EXECUTION_RISK_REPORT_MAX_AGE_HOURS))
    if generated_at is not None and max_age_hours > 0:
        clock = (now or datetime.now(timezone.utc)).astimezone(timezone.utc)
        if clock - generated_at > timedelta(hours=max_age_hours):
            return {}

    risk_map: dict[str, dict] = {}
    for row in report.get("by_symbol", []) or []:
        if not isinstance(row, dict):
            continue
        symbol = str(row.get("symbol") or row.get("ticker") or "").strip().upper()
        score = _float_or_none(row.get("execution_risk_score"))
        samples = int(_float_or_none(row.get("rebalance_orders", row.get("orders"))) or 0)
        if not symbol or score is None or samples < EXECUTION_SYMBOL_MIN_SAMPLES:
            continue
        risk_map[symbol] = {
            "score": score,
            "orders": row.get("orders", ""),
            "avg_slippage_bps": row.get("avg_slippage_bps", ""),
            "bad_slippage_rate": row.get("bad_slippage_rate", ""),
        }
    return risk_map


def _clamped_buy_scale(value: object, default: float) -> float:
    """Return a safe 0..1 buy-scale multiplier."""
    scale = _float_or_none(value)
    if scale is None:
        scale = float(default)
    return min(1.0, max(0.0, float(scale)))


def _load_execution_scorecard_state(now: datetime | None = None) -> dict:
    """
    Load the portfolio-wide execution scorecard throttle state.

    PLAIN ENGLISH: If the recent fill-quality scorecard fails, the whole order
    planner should become more cautious, not just symbols that already have
    enough per-ticker samples in the slippage report.
    """
    empty = {
        "status": "missing",
        "score": None,
        "scale": 1.0,
        "band": "none",
        "reason": "",
        "failed_checks": "",
    }
    if not EXECUTION_SCORECARD_THROTTLE_ENABLED:
        return {**empty, "status": "disabled", "reason": "execution_scorecard_throttle_disabled_sizing_unchanged"}
    if not EXECUTION_SCORECARD_FILE.exists():
        return {**empty, "reason": "execution_scorecard_missing_sizing_unchanged"}
    try:
        payload = json.loads(EXECUTION_SCORECARD_FILE.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {**empty, "status": "unreadable", "reason": "execution_scorecard_unreadable_sizing_unchanged"}

    generated_at = _parse_report_timestamp(payload.get("generated_at"))
    max_age_hours = max(0.0, float(EXECUTION_SCORECARD_MAX_AGE_HOURS))
    if generated_at is not None and max_age_hours > 0:
        clock = (now or datetime.now(timezone.utc)).astimezone(timezone.utc)
        if clock - generated_at > timedelta(hours=max_age_hours):
            return {**empty, "status": "stale", "reason": "execution_scorecard_stale_sizing_unchanged"}

    status = str(payload.get("status") or "unknown").strip().lower()
    score = _float_or_none(payload.get("score"))
    if not bool(payload.get("decision_eligible", False)):
        blockers = ",".join(str(item) for item in payload.get("decision_blockers", [])[:6])
        return {
            **empty,
            "status": "collecting",
            "band": "ineligible",
            "reason": "execution_scorecard_not_decision_eligible" + (f"_{blockers}" if blockers else ""),
        }
    failed_checks = [
        str(check.get("name", "")).strip()
        for check in payload.get("checks", []) or []
        if isinstance(check, dict) and str(check.get("status", "")).strip().lower() == "fail"
    ]

    scale = 1.0
    band = status or "unknown"
    reason = ""
    if status == "fail":
        severe_score = float(EXECUTION_SCORECARD_SEVERE_SCORE)
        if score is not None and score <= severe_score:
            scale = _clamped_buy_scale(EXECUTION_SCORECARD_SEVERE_BUY_SCALE, 0.50)
            band = "severe"
        else:
            scale = _clamped_buy_scale(EXECUTION_SCORECARD_FAIL_BUY_SCALE, 0.75)
            band = "fail"
        checks_text = ",".join(failed_checks[:6])
        score_text = "unknown" if score is None else f"{score:.2f}"
        reason = f"{band}_execution_scorecard_score_{score_text}_buy_scale_{scale:.2f}"
        if checks_text:
            reason += f"_checks_{checks_text}"

    return {
        "status": status,
        "score": score,
        "scale": scale,
        "band": band,
        "reason": reason,
        "failed_checks": ",".join(failed_checks[:8]),
    }


def _execution_risk_buy_scale(score: float | None) -> tuple[float, str]:
    """Return the buy-size multiplier for a recent execution risk score."""
    if score is None:
        return 1.0, "none"
    warn_score = float(EXECUTION_RISK_WARN_SCORE)
    high_score = max(warn_score, float(EXECUTION_RISK_HIGH_SCORE))
    if score >= high_score:
        return min(1.0, max(0.0, float(EXECUTION_RISK_HIGH_BUY_SCALE))), "high"
    if score >= warn_score:
        return min(1.0, max(0.0, float(EXECUTION_RISK_WARN_BUY_SCALE))), "warn"
    return 1.0, "low"


def _execution_risk_metadata(
    ticker: str,
    side: str,
    requested_quantity: int,
    risk_map: dict[str, dict],
    scorecard_state: dict | None = None,
) -> tuple[int, dict]:
    """
    Apply recent fill-quality evidence to one planned order quantity.

    PLAIN ENGLISH: Risky BUY orders get smaller so we do not chase poor fills.
    SELL orders are left alone because exits should not get stuck.
    """
    symbol = str(ticker).upper()
    risk = risk_map.get(symbol, {})
    score = _float_or_none(risk.get("score"))
    _, band = _execution_risk_buy_scale(score)
    scorecard_state = scorecard_state or {}
    # PLAIN ENGLISH: Poor fills now change how patiently the order is priced,
    # not how much of the approved portfolio target we buy. Silently shrinking
    # quantity created unexplained underweights without fixing per-share price.
    adjusted_quantity = int(requested_quantity)
    reason = ""
    final_scale = 1.0

    metadata = {
        "execution_risk_score": round(score, 2) if score is not None else "",
        "execution_risk_band": band,
        "execution_risk_buy_scale": final_scale,
        "execution_symbol_risk_buy_scale": 1.0,
        "execution_risk_quantity_before_scale": requested_quantity,
        "execution_risk_quantity_after_scale": adjusted_quantity,
        "execution_risk_reason": reason,
        "execution_risk_report_orders": risk.get("orders", ""),
        "execution_risk_avg_slippage_bps": risk.get("avg_slippage_bps", ""),
        "execution_risk_bad_slippage_rate": risk.get("bad_slippage_rate", ""),
        "execution_scorecard_status": scorecard_state.get("status", ""),
        "execution_scorecard_score": (
            round(float(scorecard_state["score"]), 2)
            if _float_or_none(scorecard_state.get("score")) is not None
            else ""
        ),
        "execution_scorecard_buy_scale": 1.0,
        "execution_scorecard_failed_checks": scorecard_state.get("failed_checks", ""),
        "execution_scorecard_reason": scorecard_state.get("reason", ""),
        "execution_price_policy": "two_stage_limit" if str(side).lower() in {"buy", "sell"} else "none",
    }
    return adjusted_quantity, metadata


def _round_marketable_limit(raw_price: float, side: str) -> float:
    """
    Round a limit price using US stock tick rules.

    PLAIN ENGLISH: Buy limits round up so the order stays buyable.  Sell
    limits round down so the order stays sellable.  Above $1, US stocks trade
    in pennies; below $1, Alpaca allows finer 4-decimal prices.
    """
    if raw_price <= 0 or not np.isfinite(raw_price):
        raise ValueError("limit price must be a positive finite number")
    tick = 0.0001 if raw_price < 1 else 0.01
    units = raw_price / tick
    if str(side).lower() == "buy":
        rounded = math.ceil(units - 1e-12) * tick
    else:
        rounded = math.floor(units + 1e-12) * tick
    precision = 4 if tick < 0.01 else 2
    return round(max(rounded, tick), precision)


def passive_midpoint_limit_price(bid_price: object, ask_price: object, side: str) -> float:
    """Build a non-crossing midpoint limit for the first execution attempt.

    PLAIN ENGLISH: The first order waits between buyers and sellers instead of
    immediately paying the full spread. Buy prices round down and sell prices
    round up so penny rounding cannot accidentally turn it into a marketable
    order.
    """
    bid = _float_or_none(bid_price)
    ask = _float_or_none(ask_price)
    if bid is None or ask is None or bid <= 0 or ask <= 0 or ask < bid:
        raise ValueError("A valid bid and ask are required for a passive midpoint limit")
    raw = (bid + ask) / 2.0
    tick = 0.0001 if raw < 1 else 0.01
    units = raw / tick
    rounded = math.floor(units + 1e-12) * tick if str(side).lower() == "buy" else math.ceil(units - 1e-12) * tick
    return round(max(rounded, tick), 4 if tick < 0.01 else 2)


def _stage2_offset_bps(ticker: str) -> float:
    """Return the small final cushion allowed after the passive attempt."""
    return EXECUTION_STAGE2_OFFSET_BPS_ETF if str(ticker).upper() in ETF_TICKERS else EXECUTION_STAGE2_OFFSET_BPS_OVERLAY


def _quote_age_seconds(quote: dict, *, now: datetime | None = None) -> float | None:
    """Return quote age when Alpaca supplies a timestamp."""
    stamp = _parse_broker_datetime(quote.get("quote_timestamp"))
    if stamp is None:
        return None
    clock = (now or datetime.now(timezone.utc)).astimezone(timezone.utc)
    return (clock - stamp.astimezone(timezone.utc)).total_seconds()


def _quote_is_fresh(quote: dict, *, now: datetime | None = None) -> bool:
    """Require a timestamp that is neither in the future nor too old."""
    age = _quote_age_seconds(quote, now=now)
    return age is not None and 0.0 <= age <= max(0.0, EXECUTION_QUOTE_MAX_AGE_SECONDS)


def _submission_quote(quote: dict, ticker: str) -> tuple[dict, str]:
    """Check the actual prices we will trade against, not a supplied spread."""
    checked = dict(quote)
    bid = _float_or_none(quote.get("bid_price"))
    ask = _float_or_none(quote.get("ask_price"))
    if bid is None or ask is None:
        return checked, "quote_unavailable"
    if not math.isfinite(bid) or not math.isfinite(ask) or bid <= 0 or ask <= 0 or ask < bid:
        return checked, "quote_invalid"
    # A spread is the gap between buyer and seller, divided by their midpoint.
    midpoint = bid / 2.0 + ask / 2.0
    spread = (ask - bid) / midpoint
    checked.update(bid_price=bid, ask_price=ask, quote_mid_price=midpoint, spread_pct=spread)
    if not _quote_is_fresh(checked):
        return checked, "quote_stale"
    threshold = MAX_SPREAD_PCT_ETF if ticker.upper() in ETF_TICKERS else MAX_SPREAD_PCT_OVERLAY
    if spread > threshold:
        return checked, f"spread_guard:{spread*100:.2f}%>{threshold*100:.1f}%"
    return checked, ""


def _submission_quote_with_retries(
    broker,
    ticker: str,
    side: str,
    *,
    extended_sell_retry: bool = True,
    sleep_fn=None,
) -> tuple[dict, str, int]:
    """Return one safe fresh quote without ever relaxing the spread ceiling.

    PLAIN ENGLISH: A single quote can briefly look stale or wide. Buys get the
    normal short retry budget. A sell that reduces an existing long position
    gets up to three minutes because abandoning that sale can leave the whole
    portfolio misaligned. Every attempt still has to pass the same hard limit.
    """
    ticker = str(ticker).upper()
    side = str(side).lower()
    sleeper = sleep_fn or time.sleep
    if side == "sell" and extended_sell_retry:
        attempts = SELL_QUOTE_ATTEMPTS
        retry_seconds = SELL_QUOTE_RETRY_SECONDS
    else:
        attempts = SPREAD_GUARD_QUOTE_RETRIES + 1
        retry_seconds = SPREAD_GUARD_RETRY_SECONDS

    quote: dict = {}
    reason = "quote_unavailable"
    for attempt in range(attempts):
        quote, reason = _submission_quote(broker.get_quote_snapshot(ticker), ticker)
        if not reason:
            return quote, "", attempt + 1
        if attempt + 1 < attempts:
            sleeper(retry_seconds)
    return quote, reason, attempts


def _two_stage_price_policy(order_row: dict) -> tuple[float, float, str]:
    """Turn scorecard evidence into patience and price caps, never position size."""
    status = str(order_row.get("execution_scorecard_status", "")).lower()
    failed = str(order_row.get("execution_scorecard_failed_checks", "")).lower()
    wait_seconds = float(EXECUTION_STAGE1_WAIT_SECONDS)
    offset_bps = _stage2_offset_bps(str(order_row.get("ticker", "")))
    policy = "balanced"
    if status == "warning":
        wait_seconds *= 1.5
        policy = "warning_more_patient"
    elif status == "fail" and ({"avg_slippage_bps", "bad_slippage_rate"} & set(failed.split(","))):
        wait_seconds *= 2.0
        offset_bps = min(offset_bps, 0.0 if str(order_row.get("ticker", "")).upper() in ETF_TICKERS else 1.0)
        policy = "price_failure_more_patient"
    elif status == "fail" and "fill_rate" in failed:
        wait_seconds = min(wait_seconds, 10.0)
        policy = "fill_failure_faster_reprice"
    return max(0.0, wait_seconds), max(0.0, offset_bps), policy


def marketable_limit_price(
    mark_price: float,
    side: str,
    ticker: str,
    limit_offset_bps: float | None = None,
) -> float:
    """
    Build a protective but fillable limit price from the latest mark.

    PLAIN ENGLISH: For a BUY, we allow paying only a tiny bit above the last
    price.  For a SELL, we allow selling only a tiny bit below the last price.
    This caps slippage while still behaving much like a market order.
    """
    mark = _float_or_none(mark_price)
    if mark is None or mark <= 0:
        raise ValueError("mark_price must be a positive finite number")
    side_l = str(side).lower()
    offset_bps = _limit_offset_bps(ticker) if limit_offset_bps is None else float(limit_offset_bps)
    offset = max(0.0, offset_bps) / 10_000.0
    raw = mark * (1 + offset) if side_l == "buy" else mark * (1 - offset)
    return _round_marketable_limit(raw, side_l)


def quote_based_limit_price(
    *,
    bid_price: object,
    ask_price: object,
    fallback_price: object,
    side: str,
    ticker: str,
    limit_offset_bps: float | None = None,
) -> float:
    """
    Build an optional limit from the live bid/ask instead of the last trade.

    PLAIN ENGLISH: The last trade can be stale.  If explicitly enabled with
    ALPACA_LIMIT_REFERENCE=quote, buys anchor to the current ask and sells
    anchor to the current bid.  If bid/ask is missing, this safely falls back
    to the normal last-price limit.
    """
    side_l = str(side).lower()
    quote_px = _float_or_none(ask_price if side_l == "buy" else bid_price)
    if quote_px is None or quote_px <= 0:
        quote_px = _float_or_none(fallback_price)
    if quote_px is None or quote_px <= 0:
        raise ValueError("No usable quote or fallback price for limit order")
    return marketable_limit_price(
        quote_px,
        side_l,
        ticker,
        limit_offset_bps=limit_offset_bps,
    )


