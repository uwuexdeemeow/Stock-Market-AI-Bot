def snapshot_equity(broker: AlpacaBroker) -> None:
    """
    Save a snapshot of today's account equity to the tracking CSV.

    PLAIN ENGLISH: The gauntlet needs a history of your account value over
    time to compute Sharpe ratio and max drawdown.  This saves today's
    balance so the gauntlet has data to work with.  Runs automatically
    after every order submission.
    """
    try:
        equity = broker.get_equity()
        cash = broker.get_cash()
    except Exception as e:
        print(f"    ⚠ Could not snapshot equity: {e}")
        return

    # PLAIN ENGLISH: stamp the row with New York market time, not the
    # computer's clock.  GitHub runners use UTC, so after 8 PM New York time
    # a plain datetime.now() would label today's equity as tomorrow's.
    now = datetime.now(EXECUTION_TIMEZONE).replace(tzinfo=None)
    row = {
        "date": now.strftime("%Y-%m-%d"),
        "timestamp": now.strftime("%Y-%m-%d %H:%M:%S"),
        "equity": round(equity, 2),
        "cash": round(cash, 2),
        "invested": round(equity - cash, 2),
    }

    df = pd.DataFrame([row])
    if EQUITY_FILE.exists():
        existing = pd.read_csv(EQUITY_FILE)
        # Don't duplicate same-day entries — keep latest
        existing["date"] = existing["date"].astype(str)
        existing = existing[existing["date"] != row["date"]]
        df = pd.concat([existing, df], ignore_index=True)

    atomic_write_csv(df, EQUITY_FILE)
    print(f"    ✓ Equity snapshot: ${equity:,.2f} → {EQUITY_FILE.name}")


PROTECTIVE_STOP_ORDER_TYPES = {"trailing_stop", "stop", "stop_limit"}
PROTECTIVE_EXIT_LOOKBACK_DAYS = 45


def _recent_protective_exits(
    broker: AlpacaBroker,
    *,
    lookback_days: int = PROTECTIVE_EXIT_LOOKBACK_DAYS,
    now: datetime | None = None,
) -> tuple[bool, list[dict]]:
    """List stop-loss sells that filled recently, newest first.

    PLAIN ENGLISH: the signal generator uses this to avoid buying a stock
    straight back the morning after its protective stop sold it.  Returns
    (available, exits); available is False when Alpaca could not be read.
    """
    clock = now or datetime.now(timezone.utc)
    cutoff = clock - timedelta(days=lookback_days)
    try:
        orders = _list_recent_alpaca_orders(broker)
    except Exception as exc:
        print(f"    ⚠ Could not list recent orders for stop cooldown: {exc}")
        return False, []
    exits: list[dict] = []
    for order in orders:
        order_type = str(_obj_value(order, "type", _obj_value(order, "order_type", "")) or "").lower()
        order_type = order_type.split(".")[-1]  # enum text such as "OrderType.TRAILING_STOP"
        side = str(_obj_value(order, "side", "") or "").lower().split(".")[-1]
        if order_type not in PROTECTIVE_STOP_ORDER_TYPES or side != "sell":
            continue
        filled_qty = _float_or_none(_obj_value(order, "filled_qty", 0)) or 0.0
        filled_at = _parse_broker_datetime(_obj_value(order, "filled_at"))
        if filled_qty <= 0 or filled_at is None or filled_at < cutoff:
            continue
        exits.append({
            "ticker": str(_obj_value(order, "symbol", "")).upper(),
            "filled_at": filled_at.isoformat(timespec="seconds"),
            "order_type": order_type,
            "filled_qty": filled_qty,
        })
    exits.sort(key=lambda row: row["filled_at"], reverse=True)
    return True, exits


def snapshot_status(broker: AlpacaBroker) -> None:
    """
    Write a JSON status file for Alpaca paper account state.

    PLAIN ENGLISH: The signal generator (core_satellite_alpha.py) reads a
    status file to know what the broker is currently holding — it uses
    this to decide which overlay picks to KEEP across rebalances ("sticky
    holdings").  This function writes the structure that downstream
    health and signal readers use.

    Position values come from Alpaca's API directly (market_value field),
    so quantities/values reflect live broker truth, not local trade log.
    """
    try:
        equity = broker.get_equity()
        cash = broker.get_cash()
        # Use the raw API for market_value — broker.get_positions() returns
        # quantity/avg_price only, not current market value.
        raw_positions = broker._api.list_positions()
    except Exception as e:
        print(f"    ⚠ Could not snapshot status: {e}")
        return

    # Build the status shape downstream readers expect.  Format contract:
    #   positions       : {ticker: share_count}      (dict)
    #   position_values : {ticker: dollar_value}     (dict)
    # Extra detail goes into position_details while positions remains a
    # simple ticker-to-share-count map.
    position_values: dict[str, float] = {}
    positions: dict[str, int] = {}
    position_details: list[dict] = []
    for p in raw_positions:
        try:
            ticker = str(p.symbol).upper()
            # Preserve fractional holdings; truncation corrupts cash/share comparisons.
            qty = float(p.qty)
            mv = float(p.market_value)
            positions[ticker] = qty
            position_values[ticker] = round(mv, 2)
            position_details.append({
                "ticker": ticker,
                "quantity": qty,
                "avg_price": float(p.avg_entry_price),
                "market_value": round(mv, 2),
                "unrealized_pl": round(float(p.unrealized_pl), 2),
            })
        except Exception:
            continue

    # Store only an irreversible marker. This lets evidence prove that every
    # run used the same paper account without exposing the broker account ID.
    from run_evidence import paper_account_hash

    status = {
        "broker": "alpaca",
        "paper_account_hash": paper_account_hash(getattr(broker._account, "id", "")),
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "account_equity": round(float(equity), 2),
        "account_cash": round(float(cash), 2),
        "account_invested": round(float(equity) - float(cash), 2),
        "position_count": len(position_details),
        "positions": positions,
        "position_values": position_values,
        "position_details": position_details,
    }
    exits_available, exits = _recent_protective_exits(broker)
    status["recent_protective_exits_available"] = exits_available
    status["recent_protective_exits"] = exits
    atomic_write_json(status, STATUS_FILE)
    print(f"    ✓ Status snapshot: {len(position_details)} positions → {STATUS_FILE.name}")


