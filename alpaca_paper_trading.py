def _obj_value(obj: object, key: str, default: object = None) -> object:
    """Read either dict-style or attribute-style data from Alpaca objects."""
    if isinstance(obj, dict):
        return obj.get(key, default)
    return getattr(obj, key, default)


def _parse_broker_datetime(value: object) -> datetime | None:
    """Parse an Alpaca timestamp into a timezone-aware datetime."""
    if value in (None, ""):
        return None
    if isinstance(value, pd.Timestamp):
        ts = value
    else:
        try:
            ts = pd.Timestamp(value)
        except Exception:
            return None
    if pd.isna(ts):
        return None
    if ts.tzinfo is None:
        ts = ts.tz_localize("UTC")
    else:
        ts = ts.tz_convert("UTC")
    return ts.to_pydatetime()


def _fetch_minute_bars_for_fill(
    broker: AlpacaBroker,
    ticker: str,
    filled_at: datetime,
    *,
    before_minutes: int = 15,
    after_minutes: int = 70,
) -> pd.DataFrame:
    """
    Pull minute bars around one fill.

    PLAIN ENGLISH: To know whether a fill was good or bad, we compare it with
    the minute-by-minute price around the fill.
    """
    try:
        from alpaca_sdk_adapter import minute_timeframe
    except Exception:
        return pd.DataFrame()

    start = (filled_at - timedelta(minutes=before_minutes)).astimezone(timezone.utc).isoformat()
    end = (filled_at + timedelta(minutes=after_minutes)).astimezone(timezone.utc).isoformat()
    try:
        bars = broker._api.get_bars(
            str(ticker).upper(),
            minute_timeframe(),
            start=start,
            end=end,
            adjustment="raw",
        )
        df = getattr(bars, "df", pd.DataFrame()).copy()
    except Exception:
        return pd.DataFrame()

    if df.empty:
        return df
    if isinstance(df.index, pd.MultiIndex):
        # Alpaca can return a symbol/timestamp multi-index depending on API
        # version.  Keep only this ticker and flatten back to a timestamp index.
        if "symbol" in df.index.names:
            try:
                df = df.xs(str(ticker).upper(), level="symbol")
            except Exception:
                return pd.DataFrame()
        elif "timestamp" in df.index.names:
            df.index = df.index.get_level_values("timestamp")
    if "timestamp" in df.columns:
        df.index = pd.to_datetime(df["timestamp"], utc=True, errors="coerce")
    else:
        df.index = pd.to_datetime(df.index, utc=True, errors="coerce")
    df = df[~df.index.isna()].sort_index()
    return df


def _first_bar_price_at_or_after(df: pd.DataFrame, when: pd.Timestamp) -> float | None:
    """Return the first close price at/after a timestamp."""
    if df.empty or "close" not in df.columns:
        return None
    after = df[df.index >= when]
    if after.empty:
        return None
    return _float_or_none(after["close"].iloc[0])


def _fill_minute_vwap(df: pd.DataFrame, filled_at: datetime) -> float | None:
    """Return VWAP for the fill minute, falling back to close if VWAP is absent."""
    if df.empty:
        return None
    filled_ts = pd.Timestamp(filled_at).tz_convert("UTC").floor("min")
    minute = df[(df.index >= filled_ts) & (df.index < filled_ts + pd.Timedelta(minutes=1))]
    if minute.empty:
        minute = df[(df.index >= filled_ts - pd.Timedelta(minutes=1)) & (df.index <= filled_ts + pd.Timedelta(minutes=2))]
    if minute.empty:
        return None
    for col in ("vwap", "close"):
        if col in minute.columns:
            value = _float_or_none(minute[col].dropna().iloc[0] if not minute[col].dropna().empty else None)
            if value is not None and value > 0:
                return value
    return None


def _signed_slippage_bps(side: str, fill_price: float, reference_price: float | None) -> float | None:
    """
    Positive means the fill was worse than the reference price.

    BUY: paying above VWAP is bad.  SELL: selling below VWAP is bad.
    """
    ref = _float_or_none(reference_price)
    if ref is None or ref <= 0 or fill_price <= 0:
        return None
    if str(side).lower() == "buy":
        return (fill_price - ref) / ref * 10_000
    return (ref - fill_price) / ref * 10_000


def _adverse_bps(side: str, fill_price: float, later_price: float | None) -> float | None:
    """Positive means price moved against the filled order."""
    later = _float_or_none(later_price)
    if later is None or later <= 0 or fill_price <= 0:
        return None
    if str(side).lower() == "buy":
        return (fill_price - later) / fill_price * 10_000
    return (later - fill_price) / fill_price * 10_000


def _safe_avg(values: list[float]) -> float | None:
    clean = [float(v) for v in values if v is not None and np.isfinite(float(v))]
    if not clean:
        return None
    return float(np.mean(clean))


def _safe_median(values: list[float]) -> float | None:
    clean = [float(v) for v in values if v is not None and np.isfinite(float(v))]
    if not clean:
        return None
    return float(np.median(clean))


def _measurement_counts(
    rows: list[dict],
    field: str,
    *,
    now: datetime,
    maturity_minutes: int = 0,
) -> dict:
    """Count orders that could be measured separately from those measured.

    PLAIN ENGLISH: a new fill cannot have a 60-minute result yet. It is
    "not eligible" instead of good or bad. An older fill with missing market
    bars is eligible but unmeasured, which exposes a real data-coverage gap.
    """
    eligible_rows: list[dict] = []
    measured_values: list[float] = []
    for row in rows:
        filled_at = _parse_broker_datetime(row.get("filled_at"))
        if maturity_minutes and (
            filled_at is None or now - filled_at < timedelta(minutes=maturity_minutes)
        ):
            continue
        eligible_rows.append(row)
        value = _float_or_none(row.get(field))
        if value is not None:
            measured_values.append(float(value))
    return {
        "eligible_orders": int(len(eligible_rows)),
        "measured_orders": int(len(measured_values)),
        "coverage_rate": (
            round(float(len(measured_values) / len(eligible_rows)), 4)
            if eligible_rows
            else None
        ),
        "values": measured_values,
    }


def _execution_quality_summary(rows: list[dict], *, now: datetime | None = None) -> dict:
    """Summarize a group of filled orders for dashboard comparison.

    PLAIN ENGLISH: The overall report can mix old market orders with newer
    limit orders.  This helper lets the dashboard compare those groups without
    changing how orders are placed.
    """
    clock = (now or datetime.now(timezone.utc)).astimezone(timezone.utc)
    slippage = _measurement_counts(rows, "slippage_bps", now=clock)
    adverse_5 = _measurement_counts(rows, "adverse_5m_bps", now=clock, maturity_minutes=5)
    adverse_15 = _measurement_counts(rows, "adverse_15m_bps", now=clock, maturity_minutes=15)
    adverse_30 = _measurement_counts(rows, "adverse_30m_bps", now=clock, maturity_minutes=30)
    adverse_60 = _measurement_counts(rows, "adverse_60m_bps", now=clock, maturity_minutes=60)
    slip_values = slippage["values"]
    worst_values = [r["worst_adverse_60m_bps"] for r in rows if r.get("worst_adverse_60m_bps") is not None]
    raw_bad_count = int(sum(1 for v in slip_values if float(v) > 0))
    material_bad_count = int(sum(1 for v in slip_values if float(v) > EXECUTION_BAD_SLIPPAGE_BPS))
    return {
        "orders_seen": len(rows),
        "orders_analyzed": slippage["measured_orders"],
        "eligible_orders": len(rows),
        "slippage_eligible_orders": slippage["eligible_orders"],
        "slippage_measured_orders": slippage["measured_orders"],
        "slippage_coverage_rate": slippage["coverage_rate"],
        "avg_slippage_bps": round(_safe_avg(slip_values), 2) if _safe_avg(slip_values) is not None else None,
        "median_slippage_bps": round(_safe_median(slip_values), 2) if _safe_median(slip_values) is not None else None,
        "slippage_bad_threshold_bps": EXECUTION_BAD_SLIPPAGE_BPS,
        "slippage_bad_count": material_bad_count,
        "raw_slippage_bad_count": raw_bad_count,
        "minor_bad_slippage_count": max(0, raw_bad_count - material_bad_count),
        "adverse_5m_eligible_orders": adverse_5["eligible_orders"],
        "adverse_5m_measured_orders": adverse_5["measured_orders"],
        "adverse_5m_observations": adverse_5["measured_orders"],
        "adverse_5m_coverage_rate": adverse_5["coverage_rate"],
        "adverse_5m_count": int(sum(1 for value in adverse_5["values"] if value > 0)),
        "adverse_15m_eligible_orders": adverse_15["eligible_orders"],
        "adverse_15m_measured_orders": adverse_15["measured_orders"],
        "adverse_15m_observations": adverse_15["measured_orders"],
        "adverse_15m_coverage_rate": adverse_15["coverage_rate"],
        "adverse_15m_count": int(sum(1 for value in adverse_15["values"] if value > 0)),
        "adverse_30m_eligible_orders": adverse_30["eligible_orders"],
        "adverse_30m_measured_orders": adverse_30["measured_orders"],
        "adverse_30m_observations": adverse_30["measured_orders"],
        "adverse_30m_coverage_rate": adverse_30["coverage_rate"],
        "adverse_30m_count": int(sum(1 for value in adverse_30["values"] if value > 0)),
        "adverse_60m_eligible_orders": adverse_60["eligible_orders"],
        "adverse_60m_measured_orders": adverse_60["measured_orders"],
        "adverse_60m_observations": adverse_60["measured_orders"],
        "adverse_60m_coverage_rate": adverse_60["coverage_rate"],
        "adverse_60m_count": int(sum(1 for value in adverse_60["values"] if value > 0)),
        "avg_worst_adverse_60m_bps": round(_safe_avg(worst_values), 2) if _safe_avg(worst_values) is not None else None,
        "max_worst_adverse_60m_bps": round(max(worst_values), 2) if worst_values else None,
    }


def _execution_quality_segments(rows: list[dict], *, now: datetime | None = None) -> dict:
    """Return all/market/limit/trailing-stop slices of the same fill report."""
    limit_rows = [r for r in rows if str(r.get("order_type", "")).lower() == "limit"]
    market_rows = [r for r in rows if str(r.get("order_type", "")).lower() == "market"]
    trailing_rows = [r for r in rows if str(r.get("order_type", "")).lower() == "trailing_stop"]
    protective_rows = [r for r in rows if str(r.get("order_type", "")).lower() in {"trailing_stop", "stop", "stop_limit"}]
    rebalance_rows = [r for r in rows if r not in protective_rows]
    return {
        "all_orders": _execution_quality_summary(rows, now=now),
        "rebalance_orders": _execution_quality_summary(rebalance_rows, now=now),
        "protective_stops": _execution_quality_summary(protective_rows, now=now),
        "limit_orders": _execution_quality_summary(limit_rows, now=now),
        "market_orders": _execution_quality_summary(market_rows, now=now),
        "trailing_stops": _execution_quality_summary(trailing_rows, now=now),
    }


def build_slippage_reversal_report(
    broker: AlpacaBroker,
    *,
    api_order_limit: int = 100,
    lookback_orders: int = 100,
    lookback_days: int = EXECUTION_REPORT_LOOKBACK_DAYS,
) -> dict:
    """
    Build and save a report for recent fill quality.

    PLAIN ENGLISH: This checks the latest filled Alpaca orders, compares each
    fill to the fill-minute VWAP, then checks whether price moved against the
    trade 5/15/30/60 minutes later.
    """
    report_clock = datetime.now(timezone.utc)
    report_rows: list[dict] = []
    errors: list[str] = []

    from broker_history import collect_order_history
    history = collect_order_history(broker._api, after="1970-01-01T00:00:00Z", until=report_clock, page_size=api_order_limit)
    raw_orders = history.orders
    errors.extend(history.errors)

    filled_orders = []
    for raw in raw_orders:
        filled_at = _parse_broker_datetime(_obj_value(raw, "filled_at"))
        fill_price = _float_or_none(_obj_value(raw, "filled_avg_price"))
        qty = _float_or_none(_obj_value(raw, "filled_qty"))
        # A canceled Stage-1 order can still contain a real partial fill. Keep
        # every broker order with positive filled quantity so that price
        # improvement is not lost from execution evidence.
        if qty is not None and qty > 0 and (filled_at is None or fill_price is None or fill_price <= 0):
            errors.append(f"fill_measurement_missing:{_obj_value(raw, 'id', '')}")
        if filled_at is None or fill_price is None or fill_price <= 0 or qty is None or qty <= 0:
            continue
        filled_orders.append((filled_at, raw, fill_price, qty))

    cutoff = datetime.now(timezone.utc) - timedelta(days=max(0, int(lookback_days)))
    filled_orders = [item for item in filled_orders if lookback_days <= 0 or item[0] >= cutoff]
    filled_orders.sort(key=lambda item: item[0], reverse=True)
    # Keep the old argument for callers, but measure the whole requested interval.
    measurement_sample_complete = not any(error.startswith("fill_measurement_missing:") for error in errors)

    # Join original arrival evidence to both child attempts without reconstructing old quotes.
    arrival_by_order = {}
    if PAPER_LOG_FILE.exists():
        journal = pd.read_csv(PAPER_LOG_FILE).to_dict("records")
        for saved in journal:
            for key in ("order_id", "stage1_order_id", "stage2_order_id"):
                if pd.notna(saved.get(key)):
                    arrival_by_order[str(saved[key])] = saved
    for filled_at, raw, fill_price, qty in filled_orders:
        ticker = str(_obj_value(raw, "symbol", "")).upper()
        side = str(_obj_value(raw, "side", "")).lower()
        order_type = str(_obj_value(raw, "type", "")).lower()
        if not ticker or side not in {"buy", "sell"}:
            continue

        bars = _fetch_minute_bars_for_fill(broker, ticker, filled_at)
        filled_ts = pd.Timestamp(filled_at).tz_convert("UTC")
        vwap = _fill_minute_vwap(bars, filled_at)
        row: dict[str, object] = {
            "order_id": str(_obj_value(raw, "id", "")),
            "filled_at": filled_at.isoformat(timespec="seconds"),
            "symbol": ticker,
            "side": side,
            "order_type": order_type,
            "client_order_id": str(_obj_value(raw, "client_order_id", "") or ""),
            "filled_qty": float(qty) if qty is not None and np.isfinite(qty) else None,
            "fill_price": fill_price,
            "fill_minute_vwap": round(vwap, 4) if vwap is not None else None,
            "slippage_bps": None,
            "adverse_5m_bps": None,
            "adverse_15m_bps": None,
            "adverse_30m_bps": None,
            "adverse_60m_bps": None,
            "worst_adverse_60m_bps": None,
            "best_favorable_60m_bps": None,
        }
        saved = arrival_by_order.get(row["order_id"], {})
        arrival = _float_or_none(saved.get("arrival_mid"))
        row["arrival_mid"] = arrival
        row["arrival_quote_timestamp"] = saved.get("arrival_quote_timestamp")
        row["arrival_feed"] = saved.get("arrival_feed")
        submitted_at = _parse_broker_datetime(_obj_value(raw, "submitted_at"))
        row["fill_latency_seconds"] = ((filled_at - submitted_at).total_seconds()
                                       if submitted_at is not None and filled_at >= submitted_at else None)
        quote_at = _parse_broker_datetime(saved.get("arrival_quote_timestamp"))
        row["quote_age_seconds"] = ((submitted_at - quote_at).total_seconds()
                                    if submitted_at is not None and quote_at is not None and submitted_at >= quote_at else None)

        row["arrival_shortfall_bps"] = _signed_slippage_bps(side, fill_price, arrival)
        row["original_requested_quantity"] = saved.get("original_requested_quantity")
        spread = _float_or_none(saved.get("arrival_spread_bps"))
        row["arrival_spread_bps"] = spread
        row["spread_bucket"] = "unknown" if spread is None else "0-10bps" if spread <= 10 else "10-35bps" if spread <= 35 else "over35bps"
        row["liquidity_bucket"] = saved.get("liquidity_bucket", "unknown")
        row["size_bucket"] = "under1k" if qty * fill_price < 1000 else "1k-10k" if qty * fill_price < 10000 else "over10k"
        row["session"] = filled_at.astimezone(ZoneInfo("America/New_York")).date().isoformat()
        client_order_id = str(row["client_order_id"])
        if client_order_id.endswith("-a1") or client_order_id.endswith("-a2"):
            row["parent_client_order_id"] = client_order_id[:-3]
            row["execution_stage"] = "stage1" if client_order_id.endswith("-a1") else "stage2"
        else:
            row["parent_client_order_id"] = client_order_id
            row["execution_stage"] = "legacy"
        row["parent_order_id"] = row["parent_client_order_id"] or row["order_id"]
        if order_type in {"trailing_stop", "stop", "stop_limit"}:
            row["execution_stage"] = "protective_stop"
        slip = _signed_slippage_bps(side, fill_price, vwap)
        row["slippage_bps"] = round(slip, 2) if slip is not None else None

        for minutes in (5, 15, 30, 60):
            later_px = _first_bar_price_at_or_after(
                bars,
                filled_ts + pd.Timedelta(minutes=minutes),
            )
            adverse = _adverse_bps(side, fill_price, later_px)
            row[f"adverse_{minutes}m_bps"] = round(adverse, 2) if adverse is not None else None

        if not bars.empty and "close" in bars.columns:
            window = bars[(bars.index >= filled_ts) & (bars.index <= filled_ts + pd.Timedelta(minutes=60))]
            close_prices = pd.to_numeric(window["close"], errors="coerce").dropna()
            if not close_prices.empty:
                if side == "buy":
                    adverse_series = (fill_price - close_prices) / fill_price * 10_000
                    favorable_series = (close_prices - fill_price) / fill_price * 10_000
                else:
                    adverse_series = (close_prices - fill_price) / fill_price * 10_000
                    favorable_series = (fill_price - close_prices) / fill_price * 10_000
                row["worst_adverse_60m_bps"] = round(float(adverse_series.max()), 2)
                row["best_favorable_60m_bps"] = round(float(favorable_series.max()), 2)

        report_rows.append(row)

    summary = _execution_quality_summary(report_rows, now=report_clock)
    by_symbol: list[dict] = []
    rebalance_rows = [
        row for row in report_rows
        if str(row.get("order_type", "")).lower() not in {"trailing_stop", "stop", "stop_limit"}
    ]
    if rebalance_rows:
        report_df = pd.DataFrame(rebalance_rows)
        def _numeric_series(frame: pd.DataFrame, column: str) -> pd.Series:
            if column not in frame.columns:
                return pd.Series(dtype=float)
            return pd.to_numeric(frame[column], errors="coerce").dropna()

        for symbol, grp in report_df.groupby("symbol", sort=False):
            slippage = _numeric_series(grp, "slippage_bps")
            adverse_15 = _numeric_series(grp, "adverse_15m_bps")
            worst_60 = _numeric_series(grp, "worst_adverse_60m_bps")
            orders_seen = int(len(grp))
            count = int(len(slippage))
            bad_slip_rate = float((slippage > EXECUTION_BAD_SLIPPAGE_BPS).mean()) if len(slippage) else None
            raw_bad_slip_rate = float((slippage > 0).mean()) if len(slippage) else None
            adverse_15_rate = float((adverse_15 > 0).mean()) if len(adverse_15) else None
            # PLAIN ENGLISH: Higher score means this ticker has recently been
            # harder to execute cleanly.  It is informational only; it does not
            # block trades.
            execution_risk_score = 0.0
            if len(slippage):
                execution_risk_score += max(0.0, float(slippage.mean())) * 0.5
            if len(worst_60):
                execution_risk_score += max(0.0, float(worst_60.mean())) * 0.25
            if adverse_15_rate is not None:
                execution_risk_score += adverse_15_rate * 25.0
            by_symbol.append({
                "symbol": str(symbol),
                "orders": count,
                "rebalance_orders": count,
                "orders_seen": orders_seen,
                "sample_ready": count >= EXECUTION_SYMBOL_MIN_SAMPLES,
                "avg_slippage_bps": round(float(slippage.mean()), 2) if len(slippage) else None,
                "bad_slippage_rate": round(bad_slip_rate, 3) if bad_slip_rate is not None else None,
                "raw_bad_slippage_rate": round(raw_bad_slip_rate, 3) if raw_bad_slip_rate is not None else None,
                "bad_slippage_threshold_bps": EXECUTION_BAD_SLIPPAGE_BPS,
                "adverse_15m_rate": round(adverse_15_rate, 3) if adverse_15_rate is not None else None,
                "avg_worst_adverse_60m_bps": round(float(worst_60.mean()), 2) if len(worst_60) else None,
                "execution_risk_score": round(execution_risk_score, 2),
            })
        by_symbol.sort(key=lambda row: float(row.get("execution_risk_score") or 0), reverse=True)

    from broker_history import implementation_shortfall, parent_execution_summary
    # Include zero-fill and canceled attempts in parent accounting. Arrival
    # prices and requested size come only from the recorded decision journal.
    parent_rows = []
    for raw in raw_orders:
        submitted = _parse_broker_datetime(_obj_value(raw, "submitted_at", _obj_value(raw, "created_at")))
        filled = _parse_broker_datetime(_obj_value(raw, "filled_at"))
        if lookback_days > 0 and not any(stamp is not None and stamp >= cutoff for stamp in (submitted, filled)):
            continue
        child = str(_obj_value(raw, "id", ""))
        client = str(_obj_value(raw, "client_order_id", "") or child)
        parent = client[:-3] if client.endswith(("-a1", "-a2")) else client
        saved = arrival_by_order.get(child, {})
        parent_rows.append({"order_id": child, "parent_order_id": parent,
                            "side": str(_obj_value(raw, "side", "")), "status": str(_obj_value(raw, "status", "")),
                            "filled_qty": _float_or_none(_obj_value(raw, "filled_qty")),
                            "original_requested_quantity": saved.get("original_requested_quantity"),
                            "arrival_mid": saved.get("arrival_mid")})
    from order_accounting import stage_attempt_counts
    attempts = [{key: _obj_value(raw, key) for key in
                 ("id", "client_order_id", "type", "submitted_at", "created_at", "qty", "filled_qty", "status")}
                for raw in raw_orders]
    report = {
        "stage_attempt_counts": stage_attempt_counts(attempts, start=cutoff, end=report_clock,
                                                      history_complete=history.complete),
        "schema_version": 3,
        "generated_at": report_clock.isoformat(timespec="seconds"),
        "measurement_cutoff_60m": (report_clock - timedelta(minutes=60)).isoformat(timespec="seconds"),
        "source": "alpaca_api",
        "api_order_limit": int(api_order_limit),
        "lookback_orders": int(lookback_orders),
        "lookback_days": int(lookback_days),
        "summary": summary,
        "segments": _execution_quality_segments(report_rows, now=report_clock),
        "by_symbol": by_symbol,
        "orders": report_rows,
        "errors": errors,
        "history_complete": history.complete,
        "measurement_sample_complete": measurement_sample_complete,
        "arrival_implementation_shortfall": implementation_shortfall(pd.DataFrame(report_rows)),
        "parent_execution": parent_execution_summary(pd.DataFrame(parent_rows)),
    }
    atomic_write_json(report, SLIPPAGE_REPORT_FILE)
    print(f"    ✓ Execution-quality report: {len(report_rows)} fills → {SLIPPAGE_REPORT_FILE.name}")
    return report


