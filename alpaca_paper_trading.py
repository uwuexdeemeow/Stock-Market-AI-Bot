def build_submission_order(
    order_row: dict,
    *,
    use_market_order: bool,
    use_quote_limit: bool = False,
    client_id: str | None = None,
) -> Order:
    """
    Convert one planned order row into a broker order.

    PLAIN ENGLISH: The plan says "buy 10 AAPL around $190".  This function
    turns that into either a market order or a protective limit order that
    Alpaca can submit.
    """
    ticker = str(order_row["ticker"]).upper()
    side = str(order_row["side"]).lower()
    quantity = int(order_row["quantity"])

    if use_market_order:
        order_row["submitted_order_type"] = "market"
        order_row["submitted_limit_price"] = None
        order_row["submitted_limit_reference"] = "market"
        return Order(
            ticker=ticker,
            side=side,
            quantity=quantity,
            type="market",
            client_id=client_id,
        )

    quote_anchor = _float_or_none(order_row.get("ask_price") if side == "buy" else order_row.get("bid_price"))
    if use_quote_limit and quote_anchor is not None and quote_anchor > 0:
        limit_price = quote_based_limit_price(
            bid_price=order_row.get("bid_price"),
            ask_price=order_row.get("ask_price"),
            fallback_price=order_row.get("price"),
            side=side,
            ticker=ticker,
            limit_offset_bps=_float_or_none(order_row.get("limit_offset_bps")),
        )
        order_row["submitted_limit_reference"] = "quote"
    else:
        # Prefer the limit already computed during planning.  If an older plan
        # lacks it, rebuild one from the mark price so submission still works.
        limit_price = _float_or_none(order_row.get("limit_price"))
        order_row["submitted_limit_reference"] = "last"
    if limit_price is None or limit_price <= 0:
        limit_price = marketable_limit_price(
            float(order_row["price"]),
            side,
            ticker,
            limit_offset_bps=_float_or_none(order_row.get("limit_offset_bps")),
        )
        order_row["limit_price"] = limit_price
        order_row["submitted_limit_reference"] = "last"

    order_row["submitted_order_type"] = "limit"
    order_row["submitted_limit_price"] = limit_price
    return Order(
        ticker=ticker,
        side=side,
        quantity=quantity,
        type="limit",
        limit_price=limit_price,
        client_id=client_id,
    )


def bot_client_order_id(
    order_row: dict,
    *,
    today: datetime | None = None,
    attempt: int | None = None,
) -> str:
    """
    Build the deterministic client order id used for rebalance orders.

    PLAIN ENGLISH: Alpaca rejects duplicate client_order_id values.  By making
    the id from today's date + ticker + side + quantity, a normal retry cannot
    submit the same logical trade twice. An explicitly authorized recovery run
    adds its run token so Alpaca accepts a replacement for a cancelled order.
    """
    day = (today or datetime.now(timezone.utc)).strftime("%Y%m%d")
    ticker = str(order_row["ticker"]).upper()
    side = str(order_row["side"]).lower()
    quantity = int(order_row["quantity"])
    base = f"{day}_{ticker}_{side}_{quantity}"
    raw_retry_token = str(order_row.get("client_order_id_retry_token", ""))
    retry_token = "".join(char for char in raw_retry_token if char.isalnum())[-8:]
    retry_suffix = f"-r{retry_token}" if retry_token else ""
    attempt_suffix = f"-a{int(attempt)}" if attempt is not None else ""
    suffix = retry_suffix + attempt_suffix
    return (base[: 48 - len(suffix)] + suffix)[:48]


def recovery_client_order_token(run_id: str | None = None) -> str:
    """Return a short stable token that is unique to one recovery dispatch."""
    raw = str(run_id or current_run_id())
    cleaned = "".join(char for char in raw if char.isalnum())
    return cleaned[-8:] or datetime.now(timezone.utc).strftime("%H%M%S%f")[-8:]


