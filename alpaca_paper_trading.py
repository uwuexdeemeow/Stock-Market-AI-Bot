# ─────────────────────────────────────────────────────────────────────────────

def _overlay_risk_cap(
    ticker: str,
    *,
    equity: float,
    price: float,
    current_qty: int,
    signal_target_qty: int,
    signal_target_weight: float,
) -> tuple[int, dict]:
    """Return a paper-only overlay target that is never above the signal target.

    PLAIN ENGLISH: the approved signal remains the boss.  This experimental
    guard looks at recent volatility and ATR (a typical daily price move), then
    reduces a proposed stock buy when its risk budget is smaller.  Missing or
    bad data stops an enabled experiment instead of silently removing its cap.
    """
    metadata = {
        "live_risk_cap_enabled": LIVE_RISK_CAP_ENABLED,
        "live_risk_signal_target_qty": signal_target_qty,
        "live_risk_capped_target_qty": signal_target_qty,
        "live_risk_realized_vol": "",
        "live_risk_atr_14": "",
        "live_risk_reason": "",
    }
    if not LIVE_RISK_CAP_ENABLED or ticker in ETF_TICKERS or signal_target_qty <= current_qty:
        return signal_target_qty, metadata

    # This is research behavior, not a permission to trade real money.  Fail
    # closed if somebody enables it while pointing at Alpaca's live endpoint.
    if "paper-api.alpaca.markets" not in ALPACA_BASE_URL.lower():
        raise RuntimeError("Experimental live risk cap is allowed only on Alpaca paper trading")

    path = Path(DATA_DIR) / f"{ticker.upper()}.parquet"
    if not path.exists():
        raise RuntimeError(f"Risk cap enabled but price history is missing for {ticker}")
    try:
        history = pd.read_parquet(path, columns=["High", "Low", "Close"]).sort_index()
        history = history.replace([np.inf, -np.inf], np.nan).dropna(subset=["High", "Low", "Close"])
    except Exception as exc:
        raise RuntimeError(f"Risk cap could not read valid price history for {ticker}: {exc}") from exc
    if len(history) < 21:
        raise RuntimeError(f"Risk cap needs at least 21 price rows for {ticker}")

    # True range includes overnight gaps, so ATR does not underestimate a stock
    # merely because the move happened between yesterday's close and today's open.
    previous_close = history["Close"].shift(1)
    true_range = pd.concat(
        [
            history["High"] - history["Low"],
            (history["High"] - previous_close).abs(),
            (history["Low"] - previous_close).abs(),
        ],
        axis=1,
    ).max(axis=1)
    atr_14 = float(true_range.tail(14).mean())
    realized_vol = annualized_realized_vol(history["Close"])
    if not np.isfinite(atr_14) or atr_14 <= 0 or not np.isfinite(realized_vol) or realized_vol <= 0:
        raise RuntimeError(f"Risk cap calculated invalid volatility data for {ticker}")

    # Both independent limits must agree.  The signal target is included in
    # min(), which mathematically guarantees the overlay cannot add exposure.
    vol_notional = vol_target_size(
        equity,
        realized_vol,
        target_vol_annual=LIVE_RISK_VOL_TARGET,
        max_weight=max(0.0, signal_target_weight),
    )
    vol_qty = max(0, int(vol_notional // price))
    atr_qty = position_size_with_stop(
        equity,
        price,
        atr_14,
        risk_per_trade=LIVE_RISK_PER_TRADE,
        k_atr=LIVE_RISK_ATR_MULT,
    )
    raw_cap = min(signal_target_qty, vol_qty, atr_qty)
    # A cap below today's holding must not create an unvalidated sell.  It just
    # blocks additional buying; normal approved sell logic remains untouched.
    capped_target_qty = max(current_qty, raw_cap)
    metadata.update({
        "live_risk_capped_target_qty": capped_target_qty,
        "live_risk_realized_vol": round(realized_vol, 6),
        "live_risk_atr_14": round(atr_14, 6),
        "live_risk_reason": (
            f"vol_qty={vol_qty};atr_qty={atr_qty}"
            if capped_target_qty < signal_target_qty else ""
        ),
    })
    return capped_target_qty, metadata

def generate_orders(
    broker: AlpacaBroker,
    target_weights: dict[str, float],
    force: bool = False,
) -> list[dict]:
    """
    Compare current positions to targets and generate buy/sell orders.

    PLAIN ENGLISH: Looks at what you currently own, compares it to what
    the strategy wants you to own, and figures out what to buy/sell.
    Only generates orders if the difference ("drift") is big enough to
    matter — avoids tiny trades that cost more than they're worth.
    """
    try:
        equity = float(broker.get_equity())
    except (TypeError, ValueError):
        raise RuntimeError("Invalid broker equity; refusing to generate orders")
    if not np.isfinite(equity) or equity <= 0:
        raise RuntimeError("Invalid broker equity; refusing to generate orders")
    positions = broker.get_position_map()
    releasable_stop_qty = _releasable_protective_stop_qty(broker)

    # Get current prices for all relevant tickers
    all_tickers = sorted(set(target_weights.keys()) | set(positions.keys()))
    prices: dict[str, float] = {}
    skipped_tickers: list[str] = []
    for ticker in all_tickers:
        px = broker.get_last_price(ticker)
        if np.isfinite(px) and px > 0:
            prices[ticker] = px
        else:
            skipped_tickers.append(ticker)

    # Log any tickers that couldn't get a price
    if skipped_tickers:
        print(f"    ⚠ Skipped {len(skipped_tickers)} tickers (no price): "
              f"{', '.join(skipped_tickers)}")

    execution_risk_map = _load_execution_risk_map()
    execution_scorecard_state = _load_execution_scorecard_state()
    orders = []

    for ticker in all_tickers:
        target_w = target_weights.get(ticker, 0.0)
        px = prices.get(ticker, 0.0)
        if px <= 0:
            continue

        # Current weight = (shares × price) / equity
        current_qty = positions.get(ticker, 0)
        current_value = current_qty * px
        current_w = current_value / equity if equity > 0 else 0.0

        # Target shares
        target_value = target_w * equity
        # Round to nearest share to minimize drift from target weight.
        # int() truncates toward zero and systematically under-allocates.
        # Shared pure sizing rule keeps offline accounting and paper rounding identical.
        from paper_policy import whole_share_target
        target_qty = whole_share_target(target_value, 1.0, px)

        # The experimental cap is applied only to a proposed overlay BUY.  It
        # is off by default and cannot increase the approved signal quantity.
        target_qty, live_risk = _overlay_risk_cap(
            ticker,
            equity=equity,
            price=px,
            current_qty=current_qty,
            signal_target_qty=target_qty,
            signal_target_weight=target_w,
        )

        # Drift = difference between target and current weight
        drift = abs(target_w - current_w)

        # Skip if drift is below threshold (unless forced)
        threshold = ETF_DRIFT_THRESHOLD if ticker in ETF_TICKERS else OVERLAY_DRIFT_THRESHOLD
        from paper_policy import drift_requires_trade
        if not drift_requires_trade(drift, threshold, force=force):
            continue

        # How many shares to trade
        delta_qty = target_qty - current_qty
        if delta_qty == 0:
            continue

        side = "buy" if delta_qty > 0 else "sell"
        requested_quantity = abs(delta_qty)
        broker_sellable_qty = None
        broker_reserved_stop_qty = 0
        quantity_clamped_to_sellable = False
        if side == "sell":
            immediately_sellable = _broker_sellable_qty(broker, ticker, current_qty)
            broker_reserved_stop_qty = releasable_stop_qty.get(ticker, 0)
            broker_sellable_qty = min(
                current_qty,
                immediately_sellable + broker_reserved_stop_qty,
            )
            if broker_reserved_stop_qty > 0:
                print(
                    f"    INFO SELL {ticker}: {broker_reserved_stop_qty} shares "
                    "will be released by cancelling its protective stop"
                )
            if broker_sellable_qty < requested_quantity:
                if broker_sellable_qty <= 0:
                    print(f"    WARN Skipped SELL {ticker}: broker reports 0 sellable shares")
                    continue
                print(
                    f"    WARN Clamped SELL {ticker}: requested {requested_quantity} "
                    f"shares, broker sellable {broker_sellable_qty}"
                )
                delta_qty = -broker_sellable_qty
                quantity_clamped_to_sellable = True

        adjusted_quantity, execution_risk = _execution_risk_metadata(
            ticker,
            side,
            abs(delta_qty),
            execution_risk_map,
            execution_scorecard_state,
        )
        if side == "buy" and adjusted_quantity < abs(delta_qty):
            print(
                f"    Execution risk throttle {ticker}: "
                f"{abs(delta_qty)} -> {adjusted_quantity} shares "
                f"({execution_risk['execution_risk_reason']})"
            )
            delta_qty = adjusted_quantity

        # Skip tiny orders after any broker-truth clamp or risk throttle.
        trade_value = abs(delta_qty * px)
        if trade_value < MIN_TRADE_VALUE:
            continue

        limit_offset_bps = _limit_offset_bps(ticker)
        raw_limit_price = px * (1 + limit_offset_bps / 10_000) if side == "buy" else px * (1 - limit_offset_bps / 10_000)
        limit_price = marketable_limit_price(
            px,
            side,
            ticker,
            limit_offset_bps=limit_offset_bps,
        )
        orders.append({
            "ticker": ticker,
            "side": side,
            "quantity": abs(delta_qty),
            "price": px,
            "raw_limit_price": round(raw_limit_price, 6),
            "limit_price": limit_price,
            "limit_offset_bps": limit_offset_bps,
            "trade_value": trade_value,
            "requested_quantity": requested_quantity,
            "broker_sellable_qty": broker_sellable_qty,
            "broker_reserved_stop_qty": broker_reserved_stop_qty,
            "quantity_clamped_to_sellable": quantity_clamped_to_sellable,
            **execution_risk,
            "current_weight": round(current_w, 4),
            "target_weight": round(target_w, 4),
            "drift": round(drift, 4),
            "current_qty": current_qty,
            "target_qty": target_qty,
            **live_risk,
        })

    # Sort: sells first (free up cash), then buys by size
    orders.sort(key=lambda o: (0 if o["side"] == "sell" else 1, -o["trade_value"]))
    return orders


