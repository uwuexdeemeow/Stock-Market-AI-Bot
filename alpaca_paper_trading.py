def execution_window_allowed(now: datetime | None = None) -> bool:
    """Return whether normal rebalances may be submitted in New York time."""
    clock = (now or datetime.now(timezone.utc)).astimezone(EXECUTION_TIMEZONE)
    try:
        start_hour, start_minute = (int(part) for part in EXECUTION_WINDOW_START.split(":", 1))
        end_hour, end_minute = (int(part) for part in EXECUTION_WINDOW_END.split(":", 1))
    except (TypeError, ValueError):
        return False
    start = clock.replace(hour=start_hour, minute=start_minute, second=0, microsecond=0)
    end = clock.replace(hour=end_hour, minute=end_minute, second=0, microsecond=0)
    return clock.weekday() < 5 and start <= clock <= end


# ─────────────────────────────────────────────────────────────────────────────
# RETRY HELPER — retries transient broker API failures automatically
# ─────────────────────────────────────────────────────────────────────────────

def _broker_retry(func, *, max_retries: int = 3, base_delay: float = 1.0):
    """Decorator: retry broker method on transient network errors.

    PLAIN ENGLISH: If a broker API call fails with a temporary error (network
    timeout, 5xx server error), wait a moment and try again.  After 3 failures
    in a row, give up and raise the last error.  This prevents a single hiccup
    from killing the entire daily run.
    """
    import functools
    import time as _time

    @functools.wraps(func)
    def wrapper(*args, **kwargs):
        last_exc = None
        for attempt in range(max_retries + 1):
            try:
                return func(*args, **kwargs)
            except Exception as exc:
                last_exc = exc
                exc_str = str(exc).lower()
                # Only retry on transient errors, not auth/validation failures
                is_transient = any(s in exc_str for s in (
                    "timeout", "timed out", "connection", "502", "503",
                    "504", "500", "rate limit", "429", "retry",
                ))
                if not is_transient or attempt >= max_retries:
                    raise
                delay = base_delay * (2 ** attempt)
                _time.sleep(delay)
        raise last_exc  # unreachable but satisfies type checker
    return wrapper


