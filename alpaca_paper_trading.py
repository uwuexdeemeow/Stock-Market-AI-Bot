def print_account_status(broker: AlpacaBroker) -> None:
    """Print current account state."""
    equity = broker.get_equity()
    cash = broker.get_cash()
    positions = broker.get_positions()

    print(f"\n{'═'*60}")
    print(f"  ALPACA PAPER TRADING ACCOUNT")
    print(f"{'═'*60}")
    print(f"  Equity:     ${equity:,.2f}")
    print(f"  Cash:       ${cash:,.2f}")
    print(f"  Invested:   ${equity - cash:,.2f}")
    print(f"  Market:     {'OPEN ✓' if broker.is_market_open() else 'CLOSED ✗'}")
    print(f"{'─'*60}")

    if positions:
        print(f"  {'Ticker':<8s} {'Qty':>6s} {'Avg Price':>10s} {'Value':>12s} {'Weight':>8s}")
        print(f"  {'─'*50}")
        for p in sorted(positions, key=lambda x: -x.quantity * x.avg_price):
            value = p.quantity * p.avg_price
            weight = value / equity if equity > 0 else 0
            print(f"  {p.ticker:<8s} {p.quantity:>6d} ${p.avg_price:>9.2f} ${value:>11,.2f} {weight:>7.1%}")
        invested = sum(p.quantity * p.avg_price for p in positions)
        print(f"  {'─'*50}")
        print(f"  {'TOTAL':<8s} {'':>6s} {'':>10s} ${invested:>11,.2f} {invested/equity:>7.1%}")
    else:
        print("  No positions (100% cash)")
    print()


def print_order_plan(orders: list[dict]) -> None:
    """Print the proposed orders before submission."""
    if not orders:
        print("  No orders needed — portfolio is on target.")
        return

    total_buy = sum(o["trade_value"] for o in orders if o["side"] == "buy")
    total_sell = sum(o["trade_value"] for o in orders if o["side"] == "sell")

    print(f"\n  ORDER PLAN ({len(orders)} orders)")
    print(f"  {'─'*55}")
    print(f"  {'Action':<6s} {'Ticker':<8s} {'Qty':>6s} {'Price':>9s} {'Value':>10s} "
          f"{'Current':>8s} {'Target':>8s} {'Drift':>7s}")
    print(f"  {'─'*55}")

    for o in orders:
        action = "BUY" if o["side"] == "buy" else "SELL"
        print(f"  {action:<6s} {o['ticker']:<8s} {o['quantity']:>6d} "
              f"${o['price']:>8.2f} ${o['trade_value']:>9,.2f} "
              f"{o['current_weight']:>7.1%} {o['target_weight']:>7.1%} "
              f"{o['drift']:>6.1%}")

    print(f"  {'─'*55}")
    print(f"  Total buys:  ${total_buy:,.2f}")
    print(f"  Total sells: ${total_sell:,.2f}")
    print(f"  Net flow:    ${total_buy - total_sell:+,.2f}")
    print()


def main():
    parser = argparse.ArgumentParser(
        description="Alpaca paper trading for TQQQ-enhanced core-satellite strategy"
    )
    parser.add_argument("--submit", action="store_true",
                        help="Actually submit orders (default: just show plan)")
    parser.add_argument("--status", action="store_true",
                        help="Just show account status, no order planning")
    parser.add_argument("--reconcile", action="store_true",
                        help="Check if pending orders filled and update log")
    parser.add_argument("--force", action="store_true",
                        help="Skip drift thresholds AND duplicate-day check")
    parser.add_argument("--market-order", action="store_true", default=True,
                        help="Use market orders (default)")
    args = parser.parse_args()

    # ── Connect to Alpaca ───────────────────────────────────────────────
    try:
        broker = AlpacaBroker()
        print("  ✓ Connected to Alpaca paper trading")
    except ImportError as e:
        print(f"  ✗ {e}")
        sys.exit(1)
    except ValueError as e:
        print(f"  ✗ {e}")
        sys.exit(1)
    except ConnectionError as e:
        print(f"  ✗ {e}")
        sys.exit(1)

    # ── Show account status ─────────────────────────────────────────────
    print_account_status(broker)

    if args.status:
        return

    # ── Reconcile mode: check fill statuses of pending orders ──────────
    if args.reconcile:
        reconcile_orders(broker)
        return

    # ── Load strategy signal ────────────────────────────────────────────
    try:
        signal = load_signal()
        print(f"  ✓ Signal loaded (predicted_at: {signal.get('predicted_at', 'unknown')})")
        print(f"    Strategy: {signal.get('paper_signal_type', 'unknown')}")
        print(f"    Regime:   {signal.get('current_regime', 'unknown')}")
        print(f"    Gross:    {signal.get('gross_exposure', 'unknown')}")
    except (FileNotFoundError, RuntimeError) as e:
        print(f"  ✗ {e}")
        sys.exit(1)

    # ── Parse and scale target weights ──────────────────────────────────
    raw_weights = parse_target_weights(signal)
    target_weights = scale_weights(raw_weights, MAX_GROSS_EXPOSURE)

    raw_gross = sum(abs(w) for w in raw_weights.values())
    scaled_gross = sum(abs(w) for w in target_weights.values())
    if abs(raw_gross - scaled_gross) > 0.01:
        print(f"    Scaled {raw_gross:.2f}x → {scaled_gross:.2f}x "
              f"(max gross = {MAX_GROSS_EXPOSURE:.2f}x)")

    print(f"\n  TARGET ALLOCATION")
    print(f"  {'─'*40}")
    for ticker, w in sorted(target_weights.items(), key=lambda x: -abs(x[1])):
        label = "ETF" if ticker in ETF_TICKERS else "Stock"
        print(f"  {ticker:<8s} {w:>7.1%}  ({label})")
    print(f"  {'─'*40}")
    print(f"  Gross exposure: {scaled_gross:.2%}")

    # ── Generate orders ─────────────────────────────────────────────────
    print("\n  Comparing to current positions...")
    orders = generate_orders(broker, target_weights, force=args.force)
    print_order_plan(orders)

    if not orders:
        return

    # ── Submit orders ───────────────────────────────────────────────────
    if not args.submit:
        print("  ⚠  DRY RUN — orders NOT submitted. Use --submit to execute.")
        return

    # Duplicate submission check — prevents running --submit twice in one day
    if _already_submitted_today() and not args.force:
        print("  ⚠  Orders already submitted today. Use --force to override.")
        print(f"     Check log: {PAPER_LOG_FILE}")
        return

    if not broker.is_market_open():
        print("  ⚠  Market is CLOSED. Orders will queue for next open.")
        resp = input("  Continue anyway? [y/N]: ").strip().lower()
        if resp != "y":
            print("  Aborted.")
            return

    print(f"\n  Submitting {len(orders)} orders...")
    order_ids = []
    for o in orders:
        try:
            order = Order(
                ticker=o["ticker"],
                side=o["side"],
                quantity=o["quantity"],
                type="market",
            )
            oid = broker.place_order(order)
            order_ids.append(oid)
            print(f"    ✓ {o['side'].upper()} {o['quantity']} {o['ticker']} "
                  f"→ order_id={oid[:12]}...")
        except Exception as e:
            order_ids.append(f"ERROR: {e}")
            print(f"    ✗ {o['side'].upper()} {o['quantity']} {o['ticker']} "
                  f"FAILED: {e}")

    # ── Log the submission ──────────────────────────────────────────────
    log_submission(orders, order_ids)
    print(f"\n  ✓ {len(orders)} orders submitted. Log saved → {PAPER_LOG_FILE}")

    # ── Auto-snapshot equity for gauntlet tracking ─────────────────────
    # PLAIN ENGLISH: Saves today's account value so the gauntlet can
    # compute your Sharpe ratio and drawdown over time.  Happens
    # automatically — no need to run a separate command.
    snapshot_equity(broker)

    print(f"    Check fills: python3 alpaca_paper_trading.py --reconcile")


if __name__ == "__main__":
    main()
