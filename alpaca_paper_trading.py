# ALPACA BROKER — implements the Broker abstract interface
# ─────────────────────────────────────────────────────────────────────────────

class AlpacaBroker(Broker):
    """
    Alpaca paper trading broker.

    PLAIN ENGLISH: This class talks to Alpaca's free paper trading API.
    It can check your account balance, see what you own, and buy/sell stocks.
    All trades go to the paper (fake money) account — no real money involved.
    """

    def __init__(self):
        # Import here so the rest of the script doesn't crash if alpaca isn't installed
        try:
            from alpaca_trade_api import REST
        except ImportError:
            raise ImportError(
                "alpaca-trade-api not installed. Run: pip install alpaca-trade-api"
            )

        if not ALPACA_API_KEY or not ALPACA_SECRET_KEY:
            raise ValueError(
                "Missing ALPACA_API_KEY or ALPACA_SECRET_KEY environment variables.\n"
                "Sign up free at https://alpaca.markets and set:\n"
                "  export ALPACA_API_KEY='your-key'\n"
                "  export ALPACA_SECRET_KEY='your-secret'"
            )

        self._api = REST(
            key_id=ALPACA_API_KEY,
            secret_key=ALPACA_SECRET_KEY,
            base_url=ALPACA_BASE_URL,
        )
        # Verify connection
        try:
            self._account = self._api.get_account()
        except Exception as e:
            raise ConnectionError(f"Could not connect to Alpaca: {e}")

    @_broker_retry
    def get_equity(self) -> float:
        """Get total account equity (cash + positions market value)."""
        account = self._api.get_account()
        return float(account.equity)

    @_broker_retry
    def get_cash(self) -> float:
        """Get available cash."""
        account = self._api.get_account()
        return float(account.cash)

    @_broker_retry
    def get_positions(self) -> list[Position]:
        """Get all current positions."""
        positions = self._api.list_positions()
        return [
            Position(
                ticker=str(p.symbol),
                quantity=int(float(p.qty)),
                avg_price=float(p.avg_entry_price),
            )
            for p in positions
        ]

    def get_position_map(self) -> dict[str, int]:
        """Get positions as a simple ticker → quantity dict."""
        return {p.ticker: p.quantity for p in self.get_positions()}

    @_broker_retry
    def get_sellable_qty(self, ticker: str) -> int:
        """
        Get shares Alpaca says are actually available to sell.

        PLAIN ENGLISH: A position can show 302 shares, but open stop orders or
        other broker reservations can make fewer shares sellable right now.
        `qty_available` is the broker truth that prevents sell rejections.
        """
        position = self._api.get_position(str(ticker).upper())
        qty_available = getattr(position, "qty_available", None)
        if qty_available is None:
            qty_available = getattr(position, "qty", 0)
        value = _float_or_none(qty_available)
        if value is None:
            return 0
        return max(0, int(value))

    @_broker_retry
    def place_order(self, order: Order) -> str:
        """
        Submit an order to Alpaca.

        PLAIN ENGLISH: Sends a buy or sell order.  Normal rebalances now use
        protective day limit orders; emergency exits and explicit overrides can
        still use market orders.  For trailing stop orders, Alpaca will
        automatically sell if the stock drops X% from its high point after the
        order is placed.  Returns the order ID so we can track it later.
        """
        kwargs = {
            "symbol": order.ticker,
            "qty": int(order.quantity),
            "side": order.side,
            "time_in_force": "gtc",  # trailing stops need GTC (good-til-cancelled)
        }
        if order.client_id:
            kwargs["client_order_id"] = order.client_id

        if order.type == "trailing_stop" and order.trail_percent is not None:
            # PLAIN ENGLISH: A trailing stop follows the stock price UP but
            # triggers a sell if it drops X% from the highest price seen.
            # Example: trail_percent=0.06, stock hits $100 → stop at $94.
            # If stock goes to $110, stop moves up to $103.40 automatically.
            kwargs["type"] = "trailing_stop"
            kwargs["trail_percent"] = str(round(float(order.trail_percent) * 100, 2))
            kwargs["time_in_force"] = "gtc"  # trailing stops must be GTC
        elif order.type == "limit" and order.limit_price is not None:
            kwargs["type"] = "limit"
            kwargs["limit_price"] = round(float(order.limit_price), 2)
            kwargs["time_in_force"] = "day"
        else:
            kwargs["type"] = "market"
            kwargs["time_in_force"] = "day"

        result = self._api.submit_order(**kwargs)
        return str(result.id)

    def cancel_order(self, order_id: str) -> bool:
        """Cancel a pending order."""
        try:
            self._api.cancel_order(order_id)
            return True
        except Exception:
            return False

    def cancel_all_orders(self) -> int:
        """Cancel all open orders. Returns count cancelled."""
        try:
            self._api.cancel_all_orders()
            return 1  # Alpaca doesn't return count
        except Exception:
            return 0

    def recent_fills(self, since_iso: str) -> list[Fill]:
        """Get recently filled orders."""
        try:
            orders = self._api.list_orders(
                status="filled",
                after=since_iso,
                limit=100,
            )
            return [
                Fill(
                    order_id=str(o.id),
                    ticker=str(o.symbol),
                    side=str(o.side),
                    quantity=int(float(o.filled_qty)),
                    price=float(o.filled_avg_price),
                    commission=0.0,  # Alpaca is commission-free
                )
                for o in orders
            ]
        except Exception:
            return []

    def is_market_open(self) -> bool:
        """Check if US market is currently open."""
        clock = self._api.get_clock()
        return bool(clock.is_open)

    def get_spread_pct(self, ticker: str) -> float | None:
        """Get current bid-ask spread as a percentage of midpoint.

        PLAIN ENGLISH: The 'spread' is the gap between what buyers offer (bid)
        and what sellers ask (ask).  A 0.1% spread means you lose 0.1% just by
        entering and exiting.  Wide spreads (>1%) mean the stock is illiquid
        and market orders will get bad fills.

        Returns spread as a fraction (e.g. 0.005 = 0.5%), or None if unavailable.
        """
        quote = self.get_quote_snapshot(ticker)
        return _float_or_none(quote.get("spread_pct"))

    def get_quote_snapshot(self, ticker: str) -> dict[str, float | str | None]:
        """Get current bid, ask, midpoint, and spread for one ticker.

        PLAIN ENGLISH: This asks Alpaca "what are buyers bidding and sellers
        asking right now?"  It is used for reporting and optional quote-based
        limit prices.  If Alpaca cannot provide a quote, we return blanks
        instead of crashing the trading run.
        """
        out: dict[str, float | str | None] = {
            "ticker": str(ticker).upper(),
            "bid_price": None,
            "ask_price": None,
            "quote_mid_price": None,
            "spread_pct": None,
        }
        try:
            snapshot = self._api.get_snapshot(ticker)
            quote = snapshot.latest_quote
            bid = float(quote.bp) if hasattr(quote, 'bp') else float(quote.bid_price)
            ask = float(quote.ap) if hasattr(quote, 'ap') else float(quote.ask_price)
            if bid > 0 and ask > 0:
                mid = (bid + ask) / 2
                out["bid_price"] = bid
                out["ask_price"] = ask
                out["quote_mid_price"] = mid
                out["spread_pct"] = (ask - bid) / mid
        except Exception:
            pass
        return out

    def get_last_price(self, ticker: str) -> float:
        """
        Get last traded price for a ticker with retry logic.

        PLAIN ENGLISH: Tries to fetch the latest price from Alpaca.  If the
        first attempt fails (network blip, API throttle), it waits and retries
        with exponential backoff (1s, 2s, 4s).  Logs every failure so you
        know when prices are having issues.
        """
        for attempt in range(PRICE_RETRY_ATTEMPTS):
            try:
                quote = self._api.get_latest_trade(ticker)
                return float(quote.price)
            except Exception as e1:
                # Fallback: try snapshot endpoint
                try:
                    snapshot = self._api.get_snapshot(ticker)
                    return float(snapshot.latest_trade.price)
                except Exception as e2:
                    # If not the last attempt, wait and retry
                    if attempt < PRICE_RETRY_ATTEMPTS - 1:
                        delay = PRICE_RETRY_BASE_DELAY * (2 ** attempt)
                        print(f"    ⚠ Price fetch failed for {ticker} "
                              f"(attempt {attempt+1}/{PRICE_RETRY_ATTEMPTS}): {e1} — "
                              f"retrying in {delay:.0f}s...")
                        time.sleep(delay)
                    else:
                        # Final attempt failed — log and return 0
                        print(f"    ✗ Price fetch FAILED for {ticker} after "
                              f"{PRICE_RETRY_ATTEMPTS} attempts: {e1} / {e2}")
        return 0.0


