def scale_weights(weights: dict[str, float], max_gross: float) -> dict[str, float]:
    """
    Scale weights down if total gross exposure exceeds the limit.

    PLAIN ENGLISH: If the strategy says to invest 125% of your money (using
    leverage), but you only want to invest 100%, this scales everything down
    proportionally.
    """
    try:
        max_gross_val = float(max_gross)
    except (TypeError, ValueError):
        return {}
    if not np.isfinite(max_gross_val) or max_gross_val <= 0:
        return {}

    clean: dict[str, float] = {}
    for ticker, weight in weights.items():
        try:
            weight_val = float(weight)
        except (TypeError, ValueError):
            continue
        if np.isfinite(weight_val):
            clean[str(ticker).upper()] = weight_val

    gross = sum(abs(w) for w in clean.values())
    if gross <= max_gross_val + 1e-9 or gross <= 0:
        return clean
    scale = max_gross_val / gross
    return {t: w * scale for t, w in clean.items()}


def _broker_sellable_qty(
    broker: AlpacaBroker,
    ticker: str,
    current_qty: int,
) -> int:
    """
    Return the share count that is safe to sell for one ticker.

    PLAIN ENGLISH: Order sizing starts from the position map, but Alpaca can
    reserve shares for open orders. If the broker exposes a sellable quantity,
    use it and never plan a sell larger than that broker-approved number.
    """
    fallback_qty = max(0, int(current_qty))
    getter = getattr(broker, "get_sellable_qty", None)
    if not callable(getter):
        return fallback_qty
    try:
        sellable = _float_or_none(getter(str(ticker).upper()))
    except Exception as exc:
        print(f"    WARN Could not verify sellable qty for {ticker}: {exc}")
        return fallback_qty
    if sellable is None:
        return fallback_qty
    return min(fallback_qty, max(0, int(sellable)))


def _releasable_protective_stop_qty(broker: AlpacaBroker) -> dict[str, int]:
    """Return shares reserved by stops the rebalance will cancel.

    PLAIN ENGLISH: Alpaca reports shares protected by an open trailing stop as
    unavailable to sell. The rebalance already cancels those bot-managed stops
    immediately before submitting sells. Count those reserved shares while
    building the plan so the matching sell does not disappear from the plan.
    Normal open sell orders are not counted because the bot will not cancel
    them here.
    """
    try:
        open_orders = list_open_orders(broker)
    except Exception as exc:
        print(f"    WARN Could not inspect protective stops for order planning: {exc}")
        return {}

    reserved_by_ticker: dict[str, int] = {}
    for open_order in open_orders:
        ticker = order_symbol(open_order)
        if order_side(open_order) != "sell" or order_type(open_order) not in {"trailing_stop", "stop"}:
            continue

        # Core ETF stops are cancelled only when core protection is enabled.
        # Non-ETF trailing stops are overlay protection and are cancelled by
        # cancel_overlay_trailing_stops_for_sells() before the rebalance sell.
        is_releasable_core_stop = CORE_PROTECTION_ENABLED and ticker in CORE_PROTECTION_TICKERS
        is_releasable_overlay_stop = ticker not in ETF_TICKERS
        if not (is_releasable_core_stop or is_releasable_overlay_stop):
            continue

        qty = max(0, int(order_qty(open_order)))
        reserved_by_ticker[ticker] = reserved_by_ticker.get(ticker, 0) + qty
    return reserved_by_ticker


