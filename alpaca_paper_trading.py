# ORDER RECONCILIATION — check if submitted orders actually filled
# ─────────────────────────────────────────────────────────────────────────────

def reconcile_orders(broker: AlpacaBroker) -> None:
    """
    Query Alpaca for order statuses and update the paper log.

    PLAIN ENGLISH: After you submit orders, this checks with Alpaca to see
    if they actually filled.  Updates the log CSV with the real status
    (filled, cancelled, partially_filled, etc.) so the gauntlet can
    compute accurate fill rates.
    """
    if not PAPER_LOG_FILE.exists():
        print("  No paper log found — nothing to reconcile.")
        return

    # Guard against an empty / corrupted CSV — pandas raises EmptyDataError
    # when the file is 0 bytes (the pre-fix bug used to write this when
    # zero orders survived spread/cost guards).  Also catch generic
    # ParserError so a malformed log never crashes the workflow.
    try:
        log = pd.read_csv(PAPER_LOG_FILE)
    except pd.errors.EmptyDataError:
        print("  Paper log is empty (0 bytes) — nothing to reconcile.")
        return
    except pd.errors.ParserError as exc:
        print(f"  Paper log is malformed ({exc}) — skipping reconcile.")
        return

    if log.empty or "order_id" not in log.columns:
        print("  Paper log is empty or missing order_id column.")
        return

    # Only reconcile orders that can still change at the broker.
    if "fill_status" not in log.columns:
        log["fill_status"] = "pending"

    active_statuses = {
        "",
        "accepted",
        "accepted_for_bidding",
        "new",
        "open",
        "partial",
        "partially_filled",
        "pending",
        "pending_cancel",
        "pending_new",
        "pending_replace",
        "query_failed",
        "submitted",
    }
    pending_mask = log["fill_status"].astype(str).str.lower().str.strip().isin(active_statuses)
    pending = log[pending_mask]
    overlay_sell_tickers = {
        str(row.get("ticker", "")).upper()
        for _, row in pending.iterrows()
        if str(row.get("side", "")).lower() == "sell"
        and str(row.get("ticker", "")).upper() not in ETF_TICKERS
    }

    if pending.empty:
        print("  All orders already reconciled — nothing to update.")
        return

    print(f"  Reconciling {len(pending)} pending orders...")
    updated = 0
    for idx, row in pending.iterrows():
        oid = str(row["order_id"])
        if oid.startswith("ERROR") or not oid:
            log.at[idx, "fill_status"] = "submission_failed"
            updated += 1
            continue
        try:
            order = broker._api.get_order(oid)
            status = str(order.status).lower()
            primary_qty = int(float(getattr(order, "filled_qty", 0) or 0))
            primary_price = _float_or_none(getattr(order, "filled_avg_price", None))
            stage1_oid = str(row.get("stage1_order_id", "") or "")
            stage1_qty = int(_float_or_none(row.get("stage1_filled_qty")) or 0)
            stage1_price = _float_or_none(row.get("stage1_filled_avg_price"))
            # If the final logged ID is Stage 1, its quantity is already in the
            # primary broker response and must not be counted twice.
            if stage1_oid and stage1_oid != oid:
                total_qty = stage1_qty + primary_qty
            else:
                total_qty = primary_qty
                stage1_qty = 0
            total_value = (stage1_qty * (stage1_price or 0.0)) + (primary_qty * (primary_price or 0.0))
            average_price = total_value / total_qty if total_qty > 0 and total_value > 0 else (primary_price or stage1_price)
            requested_qty = int(_float_or_none(row.get("quantity")) or 0)
            if requested_qty > 0 and total_qty >= requested_qty:
                logical_status = "filled"
            elif total_qty > 0 and status in {"canceled", "cancelled", "expired", "rejected"}:
                logical_status = "partially_filled"
            else:
                logical_status = status
            log.at[idx, "fill_status"] = logical_status
            log.at[idx, "filled_qty"] = total_qty
            if average_price is not None:
                log.at[idx, "filled_avg_price"] = average_price
                reference = _float_or_none(row.get("quote_mid_price")) or _float_or_none(row.get("price"))
                if reference is not None and reference > 0:
                    signed = (average_price - reference) / reference * 10_000.0
                    if str(row.get("side", "")).lower() == "sell":
                        signed = -signed
                    log.at[idx, "realized_slippage_bps"] = round(signed, 3)
            filled_at = pd.to_datetime(getattr(order, "filled_at", None), errors="coerce", utc=True)
            quote_time = pd.to_datetime(row.get("quote_time"), errors="coerce", utc=True)
            if pd.notna(filled_at) and pd.notna(quote_time):
                log.at[idx, "fill_latency_seconds"] = round((filled_at - quote_time).total_seconds(), 3)
            updated += 1
            status_icon = "✓" if logical_status == "filled" else "⚠"
            print(f"    {status_icon} {row['ticker']} {row['side']} "
                  f"{int(row['quantity'])} → {logical_status}")
        except Exception as e:
            log.at[idx, "fill_status"] = "query_failed"
            print(f"    ✗ {row['ticker']} order {oid[:12]}... → query failed: {e}")
            updated += 1

    atomic_write_csv(log, PAPER_LOG_FILE)
    print(f"\n  ✓ Reconciled {updated} orders. Log updated → {PAPER_LOG_FILE.name}")
    if overlay_sell_tickers:
        try:
            print("  Repairing overlay trailing stops after reconcile...")
            repair_overlay_trailing_stops(broker, tickers=overlay_sell_tickers)
        except Exception as exc:
            print(f"  ⚠ Overlay trailing-stop repair skipped after reconcile: {exc}")


